"""Render ``docs/immersed-masked-projection/REPORT.md`` from the run artefacts.

Every number in the generated markdown is read from
``docs/immersed-masked-projection/artifacts/summary.json`` (itself produced by
``scripts/immersed_masked_report.py`` from the raw run records), so the report
cannot drift from the data and no value is transcribed by hand.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def fmt(value: object, spec: str = ".4g") -> str:
    if isinstance(value, bool):
        return "PASS" if value else "FAIL"
    if isinstance(value, (int,)):
        return str(value)
    if isinstance(value, float):
        if value != value:
            return "n/a"
        return format(value, spec)
    return str(value)


def table(rows: list[list[str]], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join(["---"] * len(header)) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def render(summary: dict) -> str:
    studies = summary["studies"]
    criteria = summary["criteria"]
    out: list[str] = []
    out.append("# Immersed-solid projection: masked Poisson vs. legacy `kappa` relaxation\n")
    out.append("Generated by `scripts/immersed_write_report.py` from "
               "`artifacts/summary.json`; every number below is read from the run "
               "records, none is transcribed by hand.\n")

    out.append("\n## 1. Case, geometry and parameters\n")
    out.append("Backward-facing step (Armaly 1983 geometry family, expansion ratio "
               "exactly 2) and planar symmetric sudden expansion (area ratio 2), "
               "both represented as an *immersed mask* on a uniform Cartesian "
               "staggered-MAC grid. Non-dimensional: step height `H = U = rho = 1`, "
               "`Re_Dh = U D_h/nu` with `D_h = 2 H_in = 2`.\n")
    rows = []
    for rec in summary["run_records"]:
        rows.append([rec["case"], str(rec["cells_per_h"]), rec["arm"],
                     fmt(float(rec["expansion_ratio_realised"]), ".6f"),
                     str(rec["steps"]), fmt(float(rec["time"]), ".1f"),
                     fmt(float(rec["step_seconds"]), ".3g")])
    out.append(table(rows, ["case", "cells/H", "arm", "ER (measured)", "steps",
                            "t U/H", "s/step"]))

    out.append("\n## 2. Method\n")
    out.append(
        "- Momentum: explicit staggered-MAC advection (first-order upwind) with "
        "central diffusion; wall-adjacent faces use the half-cell ghost "
        "(`u_ghost = -u`), so no-slip is second order at the wall.\n"
        "- Projection, `masked` arm: solid cells are removed from the pressure "
        "system; every face of a solid cell carries a hard zero normal velocity, "
        "i.e. homogeneous Neumann for the correction; the outlet plane is closed "
        "with `phi = 0` outside, which makes the operator SPD and enforces "
        "`Q_out = Q_in`. The matrix is factorised once (SuperLU, MMD ordering) and "
        "reused for every step.\n"
        "- Projection, `legacy` arm: the historical Brinkman treatment -- unmasked "
        "whole-domain Poisson solve, momentum penalty sink, then a post-projection "
        "relaxation `u <- u/(1 + kappa dt)` on faces touching the body. That last "
        "operation is applied *after* continuity has been enforced, so it is the "
        "candidate root cause.\n"
        "- Mass ledger per step: `max|int_cell div u|/(U H)` over fluid and over "
        "solid cells, the net flux through the immersed surface "
        "`int_dS u.n dS` (accumulated as the spurious volume drift), the gross "
        "flux, the inlet/outlet imbalance and `max|u|` inside the body.\n")

    out.append("\n## 3. Criteria\n")
    rows = []
    for c in criteria:
        rows.append([c["id"], c["quantity"], fmt(c["value"]), fmt(c["threshold"]),
                     "PASS" if c["passed"] else "FAIL"])
    out.append(table(rows, ["criterion", "quantity", "value", "threshold", "verdict"]))

    out.append("\n## 4. Grid study\n")
    rows = []
    for key in sorted(studies):
        s = studies[key]
        rich = s.get("richardson", {})
        rows.append([key, ", ".join(str(c) for c in s["cells_per_h"]),
                     ", ".join(fmt(v, ".3f") for v in s["reattachment_over_h"]),
                     fmt(rich.get("observed_order", float("nan")), ".3f"),
                     fmt(rich.get("gci_fine_pct", float("nan")), ".3f")])
    out.append(table(rows, ["case|arm", "cells/H", "L_r/H", "p_obs", "GCI_fine %"]))

    out.append("\n### Mass ledger\n")
    rows = []
    for key in sorted(studies):
        s = studies[key]
        for k, cph in enumerate(s["cells_per_h"]):
            rows.append([key, str(cph), fmt(s["div_max_fluid"][k], ".3e"),
                         fmt(s["div_max_solid"][k], ".3e"),
                         fmt(s["drift"][k], ".3e"),
                         fmt(s["solid_speed_max"][k], ".3e"),
                         fmt(s["mass_imbalance_max"][k], ".3e")])
    out.append(table(rows, ["case|arm", "cells/H", "div_max_fluid", "div_max_solid",
                            "drift", "solid_speed_max", "mass_imbalance"]))

    if summary.get("figures"):
        out.append("\n## 5. Figures\n")
        for path in summary["figures"]:
            out.append(f"- `{Path(path).name}`")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", default="docs/immersed-masked-projection/artifacts/summary.json")
    parser.add_argument("--out", default="docs/immersed-masked-projection/REPORT.md")
    args = parser.parse_args(argv)
    summary = json.loads(Path(args.summary).read_text())
    text = render(summary)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text)
    print(text[:1200])
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())