"""Census of the repository-wide ruff backlog behind the advisory CI lint job.

The advisory ``lint (advisory)`` job runs two commands over ``src tests
scripts``: a rule check and a formatter check.  Both are tree-wide, so the job
can only turn green once the *entire* tree is clean.  This script measures that
distance exactly, per rule and per top-level directory, and can be re-run as the
backlog is burnt down (or scoped to a single package with ``--paths``).

It never modifies the tree: the rule check uses ``--output-format=json`` and the
formatter check uses ``--check`` (report-only).

Usage::

    python scripts/audit_ruff_backlog.py
    python scripts/audit_ruff_backlog.py --paths src tests --output docs/census.json
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEFAULT_PATHS = ("src", "tests", "scripts")


def _ruff() -> str:
    exe = shutil.which("ruff")
    if exe is None:
        raise SystemExit("ruff not found on PATH (pip install '.[dev]')")
    return exe


def rule_census(paths: list[str]) -> dict:
    """Per-rule and per-file counts of ``ruff check`` findings."""
    proc = subprocess.run(
        [_ruff(), "check", *paths, "--output-format=json", "--quiet"],
        cwd=REPO,
        capture_output=True,
        text=True,
    )
    # ruff exits 1 when findings exist; anything above that is a real error.
    if proc.returncode not in (0, 1):
        raise SystemExit(f"ruff check failed ({proc.returncode}): {proc.stderr}")
    findings = json.loads(proc.stdout or "[]")

    by_rule: Counter = Counter()
    by_dir: Counter = Counter()
    files: set[str] = set()
    for item in findings:
        code = item.get("code") or "?"
        path = item["filename"]
        rel = Path(path).relative_to(REPO) if Path(path).is_absolute() else Path(path)
        by_rule[code] += 1
        by_dir[rel.parts[0] if len(rel.parts) > 1 else "."] += 1
        files.add(str(rel))
    return {
        "total": len(findings),
        "files_with_findings": len(files),
        "by_rule": dict(sorted(by_rule.items(), key=lambda kv: -kv[1])),
        "by_top_level_dir": dict(sorted(by_dir.items(), key=lambda kv: -kv[1])),
    }


def format_census(paths: list[str]) -> dict:
    """Count Python files the formatter would rewrite versus files scanned."""
    probe = subprocess.run(
        [_ruff(), "format", "--check", *paths],
        cwd=REPO,
        capture_output=True,
        text=True,
    )
    if probe.returncode not in (0, 1):
        raise SystemExit(f"ruff format failed ({probe.returncode}): {probe.stderr}")
    would_reformat = [
        line.split("Would reformat: ", 1)[1].strip()
        for line in probe.stdout.splitlines()
        if line.startswith("Would reformat: ")
    ]
    tail = probe.stdout.strip().splitlines()[-1] if probe.stdout.strip() else ""
    already = total = None
    # Last line looks like "N files would be reformatted, M files already formatted".
    parts = [p.strip() for p in tail.split(",")]
    if len(parts) == 2 and parts[0].split()[0].isdigit():
        would = int(parts[0].split()[0])
        already = int(parts[1].split()[0])
        total = would + already
    return {
        "would_reformat": len(would_reformat),
        "already_formatted": already,
        "files_scanned": total,
        "first_examples": would_reformat[:5],
    }


def markdown_table(census: dict) -> str:
    """Render the census as a deterministic markdown table (no hand-typed numbers)."""
    check, fmt = census["check"], census["format"]
    lines = [
        "# ruff backlog census (generated)",
        "",
        "Generated by `python scripts/audit_ruff_backlog.py --output "
        "docs/lint-gate-106/ruff-census.json "
        "--markdown docs/lint-gate-106/census.md`; do not edit by hand.",
        "",
        "- tool: `%s` (%s)" % (census["tool"], census["ruff_version"]),
        "- paths: `%s`" % " ".join(census["paths"]),
        "- gate green: **%s**" % census["green"],
        "",
        "## `ruff check` findings per rule",
        "",
        "| rule | findings |",
        "| --- | ---: |",
    ]
    for code, count in check["by_rule"].items():
        lines.append("| `%s` | %d |" % (code, count))
    lines += ["| **total** | **%d** |" % check["total"], ""]
    lines += [
        "Files carrying at least one finding: **%d**." % check["files_with_findings"],
        "",
        "## `ruff check` findings per top-level directory",
        "",
        "| directory | findings |",
        "| --- | ---: |",
    ]
    for name, count in check["by_top_level_dir"].items():
        lines.append("| `%s` | %d |" % (name, count))
    lines += [
        "",
        "## `ruff format --check`",
        "",
        "| metric | files |",
        "| --- | ---: |",
        "| would be reformatted | %d |" % fmt["would_reformat"],
        "| already formatted | %s |" % fmt["already_formatted"],
        "| scanned | %s |" % fmt["files_scanned"],
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paths", nargs="+", default=list(DEFAULT_PATHS))
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument(
        "--markdown",
        type=Path,
        default=None,
        help="write the census as a markdown table document",
    )
    args = parser.parse_args(argv)

    census = {
        "tool": "scripts/audit_ruff_backlog.py",
        "ruff_version": subprocess.run(
            [_ruff(), "--version"], capture_output=True, text=True
        ).stdout.strip(),
        "paths": args.paths,
        "check": rule_census(args.paths),
        "format": format_census(args.paths),
    }
    total = census["check"]["total"]
    census["green"] = total == 0 and census["format"]["would_reformat"] == 0

    text = json.dumps(census, indent=1) + "\n"
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    print(text, end="")
    if args.markdown is not None:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(markdown_table(census))
    print(
        "lint gate green=%s (check findings=%d, files to reformat=%d)"
        % (census["green"], total, census["format"]["would_reformat"]),
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
