#!/usr/bin/env python
"""Reproduce the shallow-water dam-break *energy budget* verification artefacts.

    PYTHONPATH=src python scripts/run_shallow_water_energy.py \
        --out src/tensorfvm/verification/artifacts/shallow-water-energy

Writes ``summary.json`` (every number quoted in the report), ``energy_budget.png``
and ``SUMMARY.md``.  No number in the report is typed by hand: the markdown
tables are generated from the same payload that the figure is drawn from.
"""

from __future__ import annotations

import argparse
import json
import math
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from tensorfvm.shallow_water.dam_break import RITTER_DRY, STOKER_WET  # noqa: E402
from tensorfvm.shallow_water.energy import (  # noqa: E402
    certify_bore_dissipation,
    energy_budget,
    energy_convergence_study,
    exact_energy,
    bore_dissipation_rate,
)

RESOLUTIONS = (100, 200, 400, 800, 1600)
HEADLINE_N = 1600


def closed_form_energy_history(case, points=9):
    """Exact E(t) sampled by quadrature — the reference curve of the figure."""
    out = []
    for i in range(points):
        t_star = case.t_star_end * i / (points - 1)
        t = t_star * math.sqrt(case.h0 / case.gravity)
        e = exact_energy(case, t, n_quad=100_000)
        out.append({"t_star": t_star, "t": t, "energy": e["total"]})
    return out


def ritter_energy_conservation(case, points=6):
    """E(t) of the closed-form dry-bed solution must be time independent."""
    rows = []
    for i in range(points):
        t_star = case.t_star_end * i / (points - 1)
        t = t_star * math.sqrt(case.h0 / case.gravity)
        rows.append({"t_star": t_star, "energy": exact_energy(case, t, n_quad=100_000)["total"]})
    e0 = rows[0]["energy"]
    return {
        "rows": rows,
        "max_relative_drift": max(abs(r["energy"] - e0) / abs(e0) for r in rows),
    }


def figure(payload: dict, path: Path) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.4))

    ax = axes[0]
    colours = {"ritter-dry": "tab:blue", "stoker-wet": "tab:red"}
    for key, hist in payload["exact_history"].items():
        e0 = hist[0]["energy"]
        ax.plot([h["t_star"] for h in hist],
                [(h["energy"] / e0 - 1.0) * 100.0 for h in hist],
                "--", color=colours[key], lw=1.6, label=f"{key} exact")
    for key, series in payload["numeric_series"].items():
        e0 = payload["budgets"][key]["energy_initial"]
        ax.plot([s["t_star"] for s in series],
                [(s["total"] / e0 - 1.0) * 100.0 for s in series],
                "-", color=colours[key], lw=1.8,
                label=f"{key} FVM n={payload['budgets'][key]['n']}")
    ax.set_xlabel(r"$t^* = t\sqrt{g/h_0}$")
    ax.set_ylabel(r"$(E(t)/E(0) - 1)\ [\%]$")
    ax.set_title("energy history: exact vs FVM")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)

    ax = axes[1]
    for key, study in payload["convergence"].items():
        rows = study["rows"]
        ax.loglog([r["n"] for r in rows],
                  [r["energy_error"] for r in rows], "o-",
                  color=colours[key], label=f"{key} energy error")
        ax.loglog([r["n"] for r in rows],
                  [abs(r["excess_dissipation"]) for r in rows], "s--",
                  color=colours[key], alpha=0.55,
                  label=f"{key} excess dissipation")
    ref = payload["convergence"]["ritter-dry"]["rows"]
    n_ref = np.array([r["n"] for r in ref])
    e_ref = ref[0]["energy_error"] * (n_ref[0] / n_ref)
    ax.loglog(n_ref, e_ref, "k:", lw=1.2, label=r"$O(\Delta x)$ reference")
    ax.set_xlabel("cells $n$")
    ax.set_ylabel("relative energy error")
    ax.set_title("grid convergence of the energy budget")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8)

    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def summary_markdown(payload: dict) -> str:
    lines = ["# shallow-water dam-break energy budget — generated summary", ""]
    lines.append("Generated by `scripts/run_shallow_water_energy.py`; no hand-typed numbers.")
    lines.append("")
    lines.append("## Closed-form bore dissipation certification")
    lines.append("")
    lines.append("| d/t | dE/dt measured | dE/dt formula | relative error |")
    lines.append("|---|---|---|---|")
    for r in payload["certification"]["rows"]:
        lines.append(f"| {r['delta_over_t']:.2f} | {r['dE_dt_measured']:.6f} | "
                     f"{r['dE_dt_formula']:.6f} | {r['relative_error']:.2e} |")
    lines.append("")
    lines.append("## Ritter (dry bed): exact energy is time independent")
    lines.append("")
    lines.append(f"max relative drift of E(t) over t* in [0, 2]: "
                 f"**{payload['ritter_conservation']['max_relative_drift']:.2e}**")
    lines.append("")
    lines.append(f"## Headline budgets at n = {HEADLINE_N}")
    lines.append("")
    lines.append("| case | E(0) | E_exact(t*) | E_FVM(t*) | energy error | "
                 "physical dissipation | FVM dissipation |")
    lines.append("|---|---|---|---|---|---|---|")
    for key, b in payload["budgets"].items():
        lines.append(f"| {key} | {b['energy_initial']:.6f} | {b['energy_exact']:.6f} | "
                     f"{b['energy_numeric']:.6f} | {b['energy_error']:.3e} | "
                     f"{b['exact_dissipation_fraction']:.3e} | "
                     f"{b['scheme_dissipation']:.3e} |")
    lines.append("")
    lines.append("## Grid convergence")
    lines.append("")
    for key, study in payload["convergence"].items():
        lines.append(f"### {key}")
        lines.append("")
        lines.append("| n | dx | energy error | excess dissipation |")
        lines.append("|---|---|---|---|")
        for r in study["rows"]:
            lines.append(f"| {r['n']} | {r['dx']:.5f} | {r['energy_error']:.4e} | "
                         f"{r['excess_dissipation']:+.4e} |")
        lines.append("")
        lines.append("observed order (energy error): "
                     + ", ".join(f"{o:.3f}" for o in study["observed_order"]))
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="src/tensorfvm/verification/artifacts/shallow-water-energy")
    parser.add_argument("--headline-n", type=int, default=HEADLINE_N)
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    t0 = time.perf_counter()
    payload = {
        "certification": certify_bore_dissipation(),
        "ritter_conservation": ritter_energy_conservation(RITTER_DRY),
        "bore_rates": {c.key: (bore_dissipation_rate(c) if c.kind == "wet" else 0.0)
                       for c in (RITTER_DRY, STOKER_WET)},
        "budgets": {},
        "numeric_series": {},
        "exact_history": {},
        "convergence": {},
    }
    for case in (RITTER_DRY, STOKER_WET):
        budget = energy_budget(case, n=args.headline_n, samples=41)
        payload["budgets"][case.key] = {k: v for k, v in budget.items() if k != "series"}
        payload["numeric_series"][case.key] = budget["series"]
        payload["exact_history"][case.key] = closed_form_energy_history(case)
        payload["convergence"][case.key] = energy_convergence_study(
            case, resolutions=RESOLUTIONS)
    payload["wall_time_s"] = time.perf_counter() - t0

    figure(payload, out / "energy_budget.png")
    (out / "summary.json").write_text(json.dumps(payload, indent=2, default=float))
    (out / "SUMMARY.md").write_text(summary_markdown(payload))
    print(json.dumps({k: v for k, v in payload["budgets"].items()}, indent=2, default=float))
    print(f"wall {payload['wall_time_s']:.1f} s -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())