"""Grid-refinement audit of the ``CASE-FVM-CHANNEL-KMM180`` verdicts.

The case publishes a PASS/FAIL per (model, grid, grading window).  This script
asks the next question -- *is that verdict a property of the model or of the
grid?* -- using the Roache machinery in
:mod:`tensorfvm.verification.kmm180_grid`, and writes three companion
artifacts next to the case:

``grid_convergence.json``
    every number used below: the three-grid series, the observed order, the
    Richardson limit with its GCI band, the per-grid verdicts and the
    classification with the rule that produced it;
``grid_convergence.md``
    the same numbers rendered as the report (decision record, tables,
    interpretation limits);
``fig_grid_convergence.png``
    the graded RMS against grid spacing, with the ``h -> 0`` limit and its
    band.

Nothing is retyped: every number is read from ``benchmark.json``, which is
itself machine-written by ``scripts/run_case_fvm_channel_kmm180.py``.  The case
artifacts (``benchmark.json`` / ``manifest.json`` / ``REPORT.md``) are *not*
touched, so their sha256 pins stay valid.

Usage
-----
Rewrite the three artifacts::

    PYTHONPATH=src python scripts/audit_case_fvm_channel_kmm180_grid.py

Gate the committed artifacts offline (no solve, returns non-zero on drift)::

    PYTHONPATH=src python scripts/audit_case_fvm_channel_kmm180_grid.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / 'src'))

from tensorfvm.verification import kmm180_grid as grid  # noqa: E402

CASE_DIR = REPO / 'docs' / 'case-fvm-channel-kmm180'
BENCHMARK = CASE_DIR / 'benchmark.json'
OUT_JSON = CASE_DIR / 'grid_convergence.json'
OUT_MD = CASE_DIR / 'grid_convergence.md'
OUT_PNG = CASE_DIR / 'fig_grid_convergence.png'

SCHEMA = 'tensorfvm.case-fvm-channel-kmm180-grid/1'


def _sha256(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def build(benchmark_path=BENCHMARK):
    """Derive the audit record from a benchmark record (no solver call)."""
    benchmark_path = pathlib.Path(benchmark_path)
    benchmark = json.loads(benchmark_path.read_text())
    studies = grid.grid_studies(benchmark)
    try:
        source_file = str(benchmark_path.resolve().relative_to(REPO))
    except ValueError:                       # an out-of-tree copy (tests, audits)
        source_file = str(benchmark_path)
    record = {
        'schema': SCHEMA,
        'anchor': benchmark.get('anchor'),
        'source': {
            'file': source_file,
            'sha256': _sha256(benchmark_path),
            'schema': benchmark.get('schema'),
        },
        'tolerance': float(benchmark['tolerance']),
        'rule': {
            'refinement': grid.REFINEMENT,
            'safety_factor': grid.SAFETY_FACTOR,
            'order_bounds': list(grid.ORDER_BOUNDS),
            'plateau_fraction': grid.PLATEAU_FRACTION,
            'classifications': list(grid.CLASSIFICATIONS),
            'decision': ('a verdict counts as grid-robust only when every grid agrees '
                         'and the Richardson limit with its GCI band stays on that side '
                         'of the tolerance; a flat series (spread <= plateau_fraction * '
                         'tolerance) is graded as a plateau and is never extrapolated'),
        },
        'studies': studies,
        'grid_decided': grid.grid_decided(studies),
        'headline': grid.headline(studies),
    }
    return record


def _pct(value):
    return '%.3f%%' % (100.0 * value)


def _num(value, digits=6):
    if value is None:
        return 'n/a'
    return '%.*f' % (digits, value)


def render_markdown(record):
    """Render the audit record as the companion report (no hand-typed numbers)."""
    lines = []
    add = lines.append
    add('# CASE-FVM-CHANNEL-KMM180: grid-refinement audit')
    add('')
    add('Generated by `scripts/audit_case_fvm_channel_kmm180_grid.py` from '
        '`%s` (sha256 `%s`). Do not hand-edit: `--check` compares this file with '
        'a recomputation.' % (record['source']['file'], record['source']['sha256'][:16]))
    add('')
    add('## 1. Decision and alternatives')
    add('')
    add('**Decision.** For each (model, grading window) the case must state whether its')
    add('published PASS/FAIL is a property of the model or of the grid, and where the')
    add('graded RMS sits in the `h -> 0` limit.')
    add('')
    add('| alternative | why it is rejected |')
    add('|---|---|')
    add('| quote the finest grid only | the three grids disagree for SST, so "finest" '
        'is an arbitrary pick with no error bound |')
    add('| quote the coarsest grid (the current headline) | a coarse grid can pass where '
        'every refined grid fails; that is a grid artefact, not a model result |')
    add('| ablation (swap the closure, keep the grid) | does not answer the question: it '
        'moves the model, not the discretisation |')
    add('| **Richardson / GCI on the published three-grid series (used)** | the only '
        'option that yields an error bound from data the case already publishes |')
    add('')
    add('## 2. Hypothesis')
    add('')
    add('H1: the graded RMS is in the asymptotic range of the solver, so a three-grid')
    add('Richardson extrapolation returns an order inside |p| in [%.2f, %.2f] and a limit'
        % tuple(record['rule']['order_bounds']))
    add('whose GCI band does not straddle the %.1f%% tolerance.'
        % (100.0 * record['tolerance']))
    add('H0 (rejected alternative): the verdict is grid-decided, i.e. it changes with the')
    add('grid or the extrapolated limit crosses the tolerance.')
    add('')
    add('## 3. Metrics and unit of analysis')
    add('')
    add('* graded quantity: RMS relative deviation of `u+(y+)` on a grading window '
        '(dimensionless, fraction of the DNS);')
    add('* unit of analysis: one (model, window) pair, three grids (n = 64, 128, 256 cells,')
    add('  uniform refinement ratio r = %.1f);' % record['rule']['refinement'])
    add('* derived metrics: observed order p, Richardson limit f0, GCI band '
        '(Fs = %.2f).' % record['rule']['safety_factor'])
    add('')
    add('## 4. Baseline / control')
    add('')
    add('The baseline is the finest published grid (n = 256): every extrapolated number is')
    add('compared against it and against the declared %.1f%% tolerance.'
        % (100.0 * record['tolerance']))
    add('The control for the *model* effect is the three-model matrix: k-omega and')
    add('k-epsilon series that are flat across the grid isolate the grid effect from the')
    add('closure effect.')
    add('')
    add('## 5. Pre-declared thresholds and stopping rule')
    add('')
    add('* asymptotic range: sign-consistent grid differences, `|d2| < |d1|`, and order')
    add('  inside [%.2f, %.2f];' % tuple(record['rule']['order_bounds']))
    add('* plateau: whole-series spread <= %.2f x tolerance (= %.4f, i.e. %.3f pp);'
        % (record['rule']['plateau_fraction'], record['rule']['plateau_fraction'] * record['tolerance'],
           100.0 * record['rule']['plateau_fraction'] * record['tolerance']))
    add('* a verdict is `grid_robust` only if the limit +- band stays on the same side of the')
    add('  tolerance as the published verdict; otherwise `grid_decided`;')
    add('* stopping rule: the audit runs on the three published grids; no additional grid is')
    add('  solved, and no threshold is re-tuned after seeing the numbers above.')
    add('')
    add('## 6. Variables and confounders')
    add('')
    add('Controlled: reference data, Re_tau, wall treatment, model constants, grading')
    add('windows, tolerance. Changed: the cell count (the variable under test).')
    add('Confounders and how they are handled: (a) the reference substitution KMM1987 ->')
    add('Lee & Moser 2015 is measured per run inside `benchmark.json` and bounded')
    add('separately; (b) the near-wall resolution changes with n while the wall treatment')
    add('is fixed, so part of the SST trend is a `y+` effect -- the audit therefore never')
    add('claims convergence *order* as a solver property, only whether the verdict sits on')
    add('one side of the tolerance; (c) round-off is negligible at these magnitudes and is')
    add('absorbed by the plateau threshold.')
    add('')
    add('## 7. Repetition rationale')
    add('')
    add('Three grids are the minimum that determines p and f0 without assuming the order;')
    add('the series are deterministic (fixed discretisation, converged to the declared')
    add('residual), so repetition adds no information and none is claimed. The scatter')
    add('that would otherwise be attributed to noise is visible as the plateau width and')
    add('is used as the plateau threshold instead.')
    add('')
    add('## 8. Environment')
    add('')
    add('Interpreter `python >= 3.10` (see `requires-python` in `pyproject.toml`); the')
    add('audit itself needs only the standard library, the figure needs the `benchmark`')
    add('extra (matplotlib). The input record is pinned by its sha256 above, and `--check`')
    add('recomputes every number here from it, so the environment cannot silently move a')
    add('result: any drift is a gate failure, not a footnote.')
    add('')
    add('## 9. Results')
    add('')
    add('### 9.1 Per-study grid data')
    add('')
    add('| study | verdict | n = 64 | n = 128 | n = 256 | trend | spread (pp) |')
    add('|---|---|---|---|---|---|---|')
    for key, study in sorted(record['studies'].items()):
        cells = ' | '.join(_pct(v) for v in study['values'])
        add('| `%s` | %s | %s | %s | %.3f |' % (key, '/'.join(study['verdicts']), cells,
                                               study['trend'], 100.0 * study['spread']))
    add('')
    add('![grid convergence](fig_grid_convergence.png)')
    add('')
    add('### 9.2 Extrapolation and classification')
    add('')
    add('| study | p | limit | GCI band (pp) | limit +- band vs %.1f%% | class |'
        % (100.0 * record['tolerance']))
    add('|---|---|---|---|---|---|')
    for key, study in sorted(record['studies'].items()):
        gci = study['gci']
        band_pp = 'n/a' if gci is None else '%.3f' % (100.0 * gci['absolute'])
        limit = 'n/a' if study['limit'] is None else _pct(study['limit'])
        span = ('n/a' if study['limit'] is None else
                '[%s, %s]' % (_pct(study['limit_band'][0]), _pct(study['limit_band'][1])))
        order = 'n/a' if study['observed_order'] is None else '%.3f' % study['observed_order']
        if study.get('rejected_order') is not None:
            order = 'n/a (rejected %.3f)' % study['rejected_order']
        add('| `%s` | %s | %s | %s | %s | `%s` |' % (key, order, limit, band_pp, span,
                                                    study['classification']))
    add('')
    add('### 9.3 Why each study was classified that way')
    add('')
    for key, study in sorted(record['studies'].items()):
        add('* `%s` -> **%s**: %s.' % (key, study['classification'], study['reason']))
    add('')
    add('## 10. Verdict of this audit')
    add('')
    add(record['headline'])
    add('')
    if record['grid_decided']:
        add('The grid-decided entries are `%s`: their published verdicts must not be'
            % '`, `'.join(record['grid_decided']))
        add('quoted without the grid they were obtained on.')
    else:
        add('No graded verdict is grid-decided: every published verdict survives both')
        add('refinement and the extrapolated limit.')
    add('')
    add('## 11. Interpretation limits')
    add('')
    add('* The audit reuses the published grids; it cannot detect an error that is')
    add('  grid-independent (a wrong tolerance, a wrong reference, a wrong window).')
    add('* Where the series is flat (k-omega, k-epsilon) no order is claimed: the flatness')
    add('  is evidence that the grid does not control the verdict, not that the model is')
    add('  correct at another Re_tau.')
    add('* A `grid_robust` label is a statement about the discretisation only. It says')
    add('  nothing about whether the 5 % tolerance is physically appropriate.')
    add('* Two grading windows are graded because at Re_tau = 182 the physical log layer is')
    add('  only a few wall units wide; the audit inherits that limitation unchanged.')
    add('')
    return '\n'.join(lines) + '\n'


def render_figure(record, path=OUT_PNG):
    """Graded RMS against grid spacing, with the extrapolated limit and its band."""
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    stations = grid.STATIONS
    models = sorted({key.split('/')[0] for key in record['studies']})
    fig, axes = plt.subplots(1, len(stations), figsize=(5.4 * len(stations), 4.2),
                             squeeze=False, sharey=False)
    tolerance = record['tolerance']
    for ax, station in zip(axes[0], stations):
        for model in models:
            study = record['studies'].get('%s/%s' % (model, station))
            if study is None:
                continue
            h = [1.0 / n for n in study['cells']]
            ax.plot(h, study['values'], marker='o', label='%s (published)' % model)
            if study['limit'] is not None:
                ax.errorbar([0.0], [study['limit']],
                            yerr=[study['gci']['absolute']],
                            marker='s', linestyle='none', capsize=3,
                            label='%s limit ($h\\to0$)' % model)
                ax.plot([0.0, h[-1]], [study['limit'], study['values'][-1]],
                        linestyle=':', linewidth=1.0)
            else:
                ax.plot([0.0], [study['values'][-1]], marker='x', color='0.4',
                        linestyle='none', label='%s: no asymptotic range' % model)
        ax.axhline(tolerance, color='k', linestyle='--', linewidth=1.0,
                   label='tolerance %.1f%%' % (100.0 * tolerance))
        ax.set_xlabel('grid spacing $h$ (1/cells)')
        ax.set_ylabel('RMS relative deviation of $u^+(y^+)$')
        ax.set_title('grading window: %s' % station)
        ax.set_xlim(-0.0006, max(1.0 / study['cells'][0] for study in
                                 (record['studies'].get('%s/%s' % (m, station), {})
                                  for m in models)
                                 if study) * 1.05)
        ax.grid(alpha=0.3)
        ax.legend(fontsize=7)
    fig.suptitle('CASE-FVM-CHANNEL-KMM180: is the verdict a property of the model or '
                 'of the grid?')
    fig.tight_layout()
    path = pathlib.Path(path)
    fig.savefig(path, dpi=140, metadata={'Software': None})
    plt.close(fig)
    return path


def write(record, out_json=OUT_JSON, out_md=OUT_MD, out_png=OUT_PNG):
    pathlib.Path(out_json).write_text(json.dumps(record, indent=2, sort_keys=True) + '\n')
    pathlib.Path(out_md).write_text(render_markdown(record))
    render_figure(record, out_png)
    return out_json, out_md, out_png


def check(record=None, case_dir=None):
    """Compare the committed artifacts with a recomputation; return the problems.

    The artifacts are looked up next to the ``benchmark.json`` the record was
    built from, so an out-of-tree copy (a test, an audit of a branch) is gated
    against its own companions rather than against the checkout's.
    """
    record = build() if record is None else record
    case_dir = pathlib.Path(case_dir) if case_dir is not None else \
        pathlib.Path(record['source']['file']).parent
    out_json = case_dir / OUT_JSON.name
    out_md = case_dir / OUT_MD.name
    out_png = case_dir / OUT_PNG.name
    problems = []
    for path in (out_json, out_md, out_png):
        if not pathlib.Path(path).is_file():
            problems.append('missing artifact: %s' % pathlib.Path(path).name)
    if problems:
        return problems

    committed = json.loads(pathlib.Path(out_json).read_text())
    if committed.get('schema') != SCHEMA:
        problems.append('grid_convergence.json carries schema %r' % committed.get('schema'))
    if committed.get('source', {}).get('sha256') != record['source']['sha256']:
        problems.append('grid_convergence.json was produced from a different benchmark.json '
                        '(source sha256 mismatch) -> re-run the audit')
    fresh = record['studies']
    stored = committed.get('studies') or {}
    if set(fresh) != set(stored):
        problems.append('grid_convergence.json studies %s disagree with %s'
                        % (sorted(stored), sorted(fresh)))
    for key in sorted(set(fresh) & set(stored)):
        for field in ('values', 'verdicts', 'classification', 'observed_order',
                      'rejected_order', 'limit'):
            if fresh[key][field] != stored[key][field]:
                problems.append('%s.%s: committed %r vs recomputed %r'
                                % (key, field, stored[key][field], fresh[key][field]))
    if committed.get('headline') != record['headline']:
        problems.append('grid_convergence.json headline does not match the recomputation')
    if committed.get('grid_decided') != record['grid_decided']:
        problems.append('grid_convergence.json grid_decided list does not match')
    if pathlib.Path(out_md).read_text() != render_markdown(record):
        problems.append('grid_convergence.md does not match its recomputation '
                        '(regenerate with the audit script)')
    data = pathlib.Path(out_png).read_bytes()
    if not data.startswith(b'\x89PNG') or len(data) < 1024:
        problems.append('fig_grid_convergence.png is not a rendered PNG')
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='gate the committed artifacts instead of rewriting them')
    parser.add_argument('--benchmark', default=str(BENCHMARK))
    args = parser.parse_args(argv)
    record = build(args.benchmark)
    if args.check:
        problems = check(record)
        for problem in problems:
            print('PROBLEM: %s' % problem)
        if problems:
            print('GRID AUDIT: %d problem(s)' % len(problems))
            return 1
        print('GRID AUDIT: clean (%d studies, %d grid-decided)'
              % (len(record['studies']), len(record['grid_decided'])))
        print(record['headline'])
        return 0
    paths = write(record)
    print('wrote %s' % ', '.join(str(pathlib.Path(p).relative_to(REPO)) for p in paths))
    print(record['headline'])
    return 0


if __name__ == '__main__':
    raise SystemExit(main())