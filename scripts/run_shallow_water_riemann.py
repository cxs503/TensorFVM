#!/usr/bin/env python3
"""Reproduce the shallow-water Riemann-problem benchmark (all four wave patterns).

One command produces every artefact quoted in
``docs/CASE-FVM-DAMBREAK-STOKER-RIEMANN/REPORT.md``::

    PYTHONPATH=src python scripts/run_shallow_water_riemann.py \
        --out src/tensorfvm/verification/artifacts/shallow-water-riemann

Outputs: ``metrics.json`` (graded record per case at the accepted grid),
``convergence.json`` (grid series + observed orders), ``certification.json``
(jump/invariant residuals, weak-form refinement, degenerate limits),
``riemann_profiles.png``, ``riemann_convergence.png`` and ``SUMMARY.md``.

Acceptance: the anchor tolerance (5 %) on both wave positions, the star plateau
depth/velocity and the depth L1 error, plus zero interior extrema above
``EXTREMUM_FRACTION * h_ref`` ("no spurious oscillation").
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import time
from pathlib import Path

from tensorfvm.shallow_water import riemann as rp


def _git_rev() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"],
                                       text=True).strip()
    except Exception:  # pragma: no cover - not a git checkout
        return "unknown"


def _summary(payload: dict, written: list, elapsed: float) -> str:
    lines = ["# Shallow-water Riemann benchmark -- generated summary", ""]
    lines.append(f"generated by `scripts/run_shallow_water_riemann.py` "
                 f"({elapsed:.1f} s, python {platform.python_version()}, "
                 f"commit `{_git_rev()}`)")
    lines.append("")
    lines.append("| case | pattern | n | depth L1 | 1-wave err | 2-wave err | "
                 "h* err | u* err | extrema | pass |")
    lines.append("|---|---|---:|---:|---:|---:|---:|---:|---:|:--:|")
    for name, record in payload["cases"].items():
        m, d = record["metrics"], record["discretisation"]
        lines.append(
            f"| {name} | {record['case']['pattern']} | {d['n']} | "
            f"{100 * m['depth_l1']:.4f} % | "
            f"{100 * m['wave_left']['rel_error']:.3f} % | "
            f"{100 * m['wave_right']['rel_error']:.3f} % | "
            f"{100 * m['plateau']['depth_rel_error']:.3f} % | "
            f"{100 * m['plateau']['velocity_rel_error']:.3f} % | "
            f"{m['extremum_count']} | {'PASS' if record['verdict']['pass'] else 'FAIL'} |")
    lines.append("")
    lines.append("Files: " + ", ".join(sorted(p.name for p in written)))
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=(
        "src/tensorfvm/verification/artifacts/shallow-water-riemann"))
    parser.add_argument("--accepted-n", type=int, default=3200)
    parser.add_argument("--resolutions", default="400,800,1600,3200")
    parser.add_argument("--cfl", type=float, default=0.4)
    parser.add_argument("--order", type=int, default=2)
    args = parser.parse_args(argv)

    resolutions = tuple(int(x) for x in args.resolutions.split(","))
    started = time.time()
    out = Path(args.out)
    written = rp.write_artifacts(out, resolutions=resolutions,
                                 accepted_n=args.accepted_n, cfl=args.cfl,
                                 order=args.order)
    payload = json.loads((out / "metrics.json").read_text())
    elapsed = time.time() - started
    summary = _summary(payload, written, elapsed)
    (out / "SUMMARY.md").write_text(summary)
    written.append(out / "SUMMARY.md")
    manifest = {
        "command": " ".join([Path(sys.argv[0]).name] + sys.argv[1:]),
        "argv": sys.argv[1:],
        "commit": _git_rev(),
        "python": platform.python_version(),
        "elapsed_s": round(elapsed, 2),
        "tolerance": rp.TOLERANCE,
        "accepted_n": args.accepted_n,
        "resolutions": list(resolutions),
        "files": sorted(p.name for p in written),
        "all_pass": all(record["verdict"]["pass"]
                        for record in payload["cases"].values()),
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(summary)
    print(f"artefacts written to {out}/ ({len(written) + 1} files)")
    return 0 if manifest["all_pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())