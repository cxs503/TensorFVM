#!/usr/bin/env python3
"""Oblique (rotated) Ritter/Stoker dam-break verification artifacts.

Every number quoted in ``docs/case-fvm-dambreak-stoker-oblique/REPORT.md`` is
produced here::

    PYTHONPATH=src python scripts/run_shallow_water_dam_break_oblique.py \
        --out src/tensorfvm/verification/artifacts/shallow-water-dam-break-oblique \
        --grids 240 480

The study rotates the dam line of the anchor ``CASE-FVM-DAMBREAK-STOKER``
(``0`` = axis-aligned control, ``atan(1/2)`` and ``45 deg`` = oblique) on a
square Cartesian grid and grades the binned **normal** profile against the
rotated exact solution with the anchor's own estimators
(:mod:`tensorfvm.shallow_water.dam_break2d_oblique`).

Outputs: ``metrics.json``, ``SUMMARY.md``, ``oblique_profiles.png`` and
``profile_<case>_<angle>.csv`` inside ``--out``.
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

from tensorfvm.shallow_water import TOLERANCE, t_star_to_time
from tensorfvm.shallow_water.dam_break2d_oblique import (
    ANGLES_DEG,
    DOMAIN,
    OBLIQUE_AGREEMENT_MAX,
    OBLIQUE_CASES,
    STRIP_HALF_WIDTH,
    estimator_zero_bias,
    isotropy_rows,
    run_oblique_case,
    write_artifacts_oblique,
)


def _git_rev() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True,
                              check=False).stdout.strip() or "unknown"
    except OSError:  # pragma: no cover - git always present in the worktree
        return "unknown"


def _table(rows, header) -> str:
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def build_summary(payload: dict) -> str:
    out = []
    t_star = payload["t_star"]
    out.append("# CASE-FVM-DAMBREAK-STOKER / oblique dam-line verification — "
               "artifacts\n")
    out.append(f"Generated by `scripts/run_shallow_water_dam_break_oblique.py` "
               f"at commit `{payload['meta']['git_rev']}` on "
               f"{payload['meta']['host']} "
               f"({payload['meta']['python'].split()[0]}), "
               f"total wall time {payload['meta']['wall_time_s']:.0f} s.\n")
    out.append("Domain side %.1f m, graded strip |p| <= %.1f m, "
               "t* = %.1f, acceptance %.0f %%, declared angle-agreement gate "
               "%.1f pp.\n" % (payload["domain"], payload["strip_half_width"],
                               t_star, 100.0 * TOLERANCE,
                               100.0 * OBLIQUE_AGREEMENT_MAX))

    for key, block in payload["cases"].items():
        out.append(f"\n## {key} (h0 = {block['h0']}, h1 = {block['h1']})\n")
        rows = []
        for grid in block["grids"]:
            for run in grid["runs"]:
                m = run["metrics"]
                rows.append([
                    grid["n"], run["angle_deg"],
                    "%.3f" % (100.0 * m["headline_error"]),
                    "%.3f" % (100.0 * m["front_level_error"])
                    if "front_level_error" in m else "—",
                    "%.4f" % (100.0 * m["step_ratio_error"])
                    if "step_ratio_error" in m else "—",
                    "%.3f" % (100.0 * m["depth_l1"]),
                    "%d" % m["local_extrema"],
                    "%.2e" % m["mass_drift"],
                    "%.2e" % m["strip_mass_error"],
                    "yes" if run["verdict"]["pass"] else "NO",
                ])
        out.append(_table(rows, ["n", "angle [deg]", "front [%]", "level-cross [%]",
                                 "level step [%]", "depth L1 [%]", "extrema",
                                 "global mass drift", "strip mass error",
                                 "verdict"]))
        out.append("\n### isotropy (rotation consistency vs the 0 deg control)\n")
        rows = []
        for grid in block["grids"]:
            iso = grid["isotropy"]
            for row in iso["rows"]:
                rows.append([
                    iso["n"], "%6.3f" % row["angle_deg"],
                    "%.3f" % (100.0 * row["headline_error"]),
                    "%+.3f" % (100.0 * row["delta_headline_vs_control"]),
                    "%+.3f" % (100.0 * row["delta_depth_l1_vs_control"]),
                    "yes" if row["direction_consistent"] else "NO",
                ])
            out.append("")
        out.append(_table(rows, ["n", "angle [deg]", "front err [%]",
                                 "delta vs control [pp]", "delta L1 [pp]",
                                 "within %.1f pp" % (100.0 * OBLIQUE_AGREEMENT_MAX)]))
        out.append("\n### wave-position series (acceptance quantity x_f(t))\n")
        rows = []
        for grid in block["grids"]:
            for run in grid["runs"]:
                series = run["series"]
                rows.append([
                    grid["n"], run["angle_deg"],
                    "%.3f" % (100.0 * series["max_graded_error"]),
                    "%.3f" % (100.0 * series["max_headline_error"]),
                    "%d/%d" % (series["graded_samples"], series["total_samples"]),
                    "yes" if series["pass"] else "NO",
                ])
        out.append(_table(rows, ["n", "angle [deg]", "max series [%]",
                                 "max oracle-free [%]", "graded",
                                 "series verdict"]))
    out.append("\n## estimator zero-bias (applied to the exact profile)\n")
    rows = []
    for key, zb in payload["estimator_zero_bias"].items():
        rows.append([key, "%.2e" % zb["headline_error"],
                     "%.2e" % zb["depth_l1"], zb["local_extrema"]])
    out.append(_table(rows, ["case", "front/bore error", "L1", "extrema"]))
    if payload["honest_fail"]:
        out.append("\n## honest FAIL (grids / gates that did not meet the bar)\n")
        rows = [[f["case"], f["n"], f["angle_deg"], ", ".join(f["failing_criteria"]),
                 f["detail"]] for f in payload["honest_fail"]]
        out.append(_table(rows, ["case", "n", "angle [deg]", "failing", "detail"]))
    else:
        out.append("\n## honest FAIL\n\nNone: every graded gate passed on every "
                   "grid and angle in this sweep.\n")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=(
        "src/tensorfvm/verification/artifacts/shallow-water-dam-break-oblique"))
    parser.add_argument("--grids", type=int, nargs="+", default=[240, 480])
    parser.add_argument("--domain", type=float, default=DOMAIN)
    parser.add_argument("--strip", type=float, default=STRIP_HALF_WIDTH)
    parser.add_argument("--csv", action="store_true",
                        help="also dump every graded normal profile to CSV")
    args = parser.parse_args(argv)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    wall0 = time.perf_counter()
    payload = {
        "slug": "CASE-FVM-DAMBREAK-STOKER",
        "variant": "oblique dam line (rotated exact solution)",
        "domain": float(args.domain),
        "strip_half_width": float(args.strip),
        "grids": [int(n) for n in args.grids],
        "angles_deg": [float(a) for a in ANGLES_DEG],
        "t_star": 2.0,
        "tolerance": TOLERANCE,
        "agreement_max": OBLIQUE_AGREEMENT_MAX,
        "cases": {},
        "meta": {"git_rev": _git_rev(), "host": platform.node(),
                 "python": sys.version.split()[0]},
    }
    honest_fail = []
    for key, case in OBLIQUE_CASES.items():
        block = {"h0": case.h0, "h1": case.h1, "case": key,
                 "t_star": case.t_star_end, "n": int(args.grids[-1]),
                 "runs": [], "grids": []}
        for n in args.grids:
            runs = []
            for angle in ANGLES_DEG:
                run = run_oblique_case(case, angle, int(n), args.domain,
                                       strip_half_width=args.strip)
                runs.append(run)
                m = run["metrics"]
                print("%-10s n=%-4d angle=%6.2f  front=%6.3f%%  L1=%5.3f%%  "
                      "extrema=%d  drift=%.1e  steps=%d  wall=%.0fs"
                      % (key, n, angle, 100.0 * m["headline_error"],
                         100.0 * m["depth_l1"], m["local_extrema"],
                         m["mass_drift"], run["discretisation"]["steps"],
                         run["discretisation"]["wall_time_s"]), flush=True)
                if not run["verdict"]["pass"]:
                    honest_fail.append({
                        "case": key, "n": int(n), "angle_deg": float(angle),
                        "failing_criteria": run["verdict"]["failing"],
                        "detail": "front %.3f%% / L1 %.3f%% / extrema %d"
                                  % (100.0 * m["headline_error"],
                                     100.0 * m["depth_l1"],
                                     m["local_extrema"]),
                    })
                if not run["series"]["pass"]:
                    honest_fail.append({
                        "case": key, "n": int(n), "angle_deg": float(angle),
                        "failing_criteria": ["front_series<5%"],
                        "detail": "max graded series %.3f%% over %d samples"
                                  % (100.0 * run["series"]["max_graded_error"],
                                     run["series"]["graded_samples"]),
                    })
                if args.csv:
                    prof = run["profile"]
                    path = out / ("profile_%s_%d_%05.1f.csv"
                                  % (key, n, angle))
                    with path.open("w") as fh:
                        fh.write("s,h_numeric,h_exact,u_n\n")
                        for row in zip(prof["s"], prof["h_numeric"],
                                       prof["h_exact"], prof["u_n"]):
                            fh.write("%.9g,%.9g,%.9g,%.9g\n" % tuple(row))
            grid = {"n": int(n), "runs": runs}
            grid["isotropy"] = isotropy_rows(case, runs)
            block["grids"].append(grid)
        block["runs"] = block["grids"][-1]["runs"]  # figure uses the fine grid
        payload["cases"][key] = block
        payload["estimator_zero_bias"] = payload.get("estimator_zero_bias", {})
        payload["estimator_zero_bias"][key] = estimator_zero_bias(
            case, t_star_to_time(case.t_star_end, case.h0, case.gravity),
            n=int(args.grids[-1]))
    payload["honest_fail"] = honest_fail
    payload["verdict"] = {
        "all_endstate_pass": bool(all(
            run["verdict"]["pass"] for block in payload["cases"].values()
            for grid in block["grids"] for run in grid["runs"])),
        "all_series_pass": bool(all(
            run["series"]["pass"] for block in payload["cases"].values()
            for grid in block["grids"] for run in grid["runs"])),
        "all_direction_consistent": bool(all(
            grid["isotropy"]["all_direction_consistent"]
            for block in payload["cases"].values() for grid in block["grids"])),
        "honest_fail_count": len(honest_fail),
        "tolerance_percent": 100.0 * TOLERANCE,
    }
    payload["meta"]["wall_time_s"] = time.perf_counter() - wall0
    payload["SUMMARY"] = build_summary(payload)
    paths = write_artifacts_oblique(out, payload)
    (out / "metrics.json").write_text(
        json.dumps({k: v for k, v in payload.items() if k != "SUMMARY"},
                   indent=1, sort_keys=True))
    manifest = {
        "slug": payload["slug"],
        "variant": payload["variant"],
        "git_rev": payload["meta"]["git_rev"],
        "grids": payload["grids"],
        "angles_deg": payload["angles_deg"],
        "artifacts": paths,
        "verdict": payload["verdict"],
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1,
                                                 sort_keys=True))
    print(json.dumps(payload["verdict"], indent=1))
    print("artifacts:", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())