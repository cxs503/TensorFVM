#!/usr/bin/env python
"""Grade the forward-step grid triple and write the machine-readable verdict.

    python scripts/forward_step_grid_triple.py \
        --runs /tmp/fs_run,/path/to/fields_only_dir \
        --out docs/repro-fvm-forward-step/artifacts/grid_triple.json \
        --md docs/repro-fvm-forward-step/RESULT-grid-triple.md

Every field dump written by ``scripts/forward_step_study.py``
(``fields_<nx>x<ny>.npz``) is re-graded here with
:mod:`tensorfvm.compressible.forward_step_benchmark`, so no number in the
produced JSON / markdown is typed by hand.  A ``run_<nx>x<ny>.json`` next to a
field dump supplies the step count, wall time and the conservation budgets; a
dump without that metadata is still graded but its budget identities are marked
``not_available`` instead of being invented.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

import torch  # noqa: E402

from tensorfvm.compressible.forward_step import (  # noqa: E402
    ForwardStepConfig,
    T_END,
)
from tensorfvm.compressible.forward_step_benchmark import (  # noqa: E402
    GRID_OF_RECORD,
    TOL,
    WITHDRAWN,
    convergence,
    grade_run,
)

BUDGET_LABELS = ("mass_budget_drift", "energy_budget_drift")


def _tags(run_dir: Path) -> list:
    tags = [p.stem.split("_", 1)[1] for p in Path(run_dir).glob("fields_*.npz")]
    tags.sort(key=lambda g: int(g.split("x")[0]) * int(g.split("x")[1]))
    return tags


def _load(run_dir: Path, tag: str):
    import numpy as np

    with np.load(run_dir / f"fields_{tag}.npz") as npz:
        prim = {k: torch.as_tensor(npz[k]).double() for k in ("rho", "u", "v", "p")}
    nx, ny = (int(v) for v in tag.lower().split("x"))
    meta_path = run_dir / f"run_{tag}.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
    t_end = meta.get("config", {}).get("t_end", T_END)
    return prim, ForwardStepConfig(nx=nx, ny=ny, t_end=t_end), meta


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", required=True,
                    help="comma separated directories holding fields_<tag>.npz")
    ap.add_argument("--out", default=str(ROOT / "docs" / "repro-fvm-forward-step"
                                         / "artifacts" / "grid_triple.json"))
    ap.add_argument("--md", default=str(ROOT / "docs" / "repro-fvm-forward-step"
                                        / "RESULT-grid-triple.md"))
    args = ap.parse_args(argv)

    grades, runs = [], {}
    for run_dir in (Path(p).expanduser() for p in args.runs.split(",") if p.strip()):
        for tag in _tags(Path(run_dir)):
            prim, cfg, meta = _load(Path(run_dir), tag)
            g = grade_run(prim, cfg, meta)
            if not meta.get("budget"):
                for item in g["items"]:
                    if item["quantity"] in BUDGET_LABELS:
                        item["status"] = "not_available"
                        item["pass"] = False
                active = [i for i in g["items"]
                          if i["tolerance"] == TOL and i["status"] == "graded"]
                g["verdict"]["n_graded"] = len(active)
                g["verdict"]["n_graded_pass"] = sum(1 for i in active if i["pass"])
                g["all_graded_pass"] = all(i["pass"] for i in active)
            g["run_dir"] = str(run_dir)
            g["troubled_repairs"] = meta.get("troubled_repairs")
            g["positivity_fixes"] = meta.get("positivity_fixes")
            grades.append(g)
            runs[tag] = g
            print(f"[grid-triple] {tag}: n_graded={g['verdict']['n_graded']} "
                  f"pass={g['verdict']['n_graded_pass']} all_pass={g['all_graded_pass']}")

    if not grades:
        raise SystemExit("no fields_*.npz found under --runs")

    conv = convergence(grades)
    record = [g for g in grades
              if [g["grid"][0], g["grid"][1]] == list(GRID_OF_RECORD)]
    payload = {
        "case": "CASE-FORWARD-STEP",
        "tolerance": TOL,
        "grid_of_record": list(GRID_OF_RECORD),
        "withdrawn": dict(WITHDRAWN),
        "grids": [g["grid"] for g in grades],
        "runs": runs,
        "convergence": conv,
        "record": record[0] if record else None,
        "verdict": record[0]["verdict"] if record else None,
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n")

    lines = ["# CASE-FORWARD-STEP — grid triple result (machine generated)", "",
             "> Generated by `scripts/forward_step_grid_triple.py` from the field dumps; "
             "no number below is typed by hand.", "",
             f"Pre-registered tolerance: {100 * TOL:.0f} %.  Grid of record: "
             f"{GRID_OF_RECORD[0]} x {GRID_OF_RECORD[1]}.", ""]
    active = [k for k in runs[next(iter(runs))]["items"]
              if True]
    lines += ["## Graded criteria (status = graded)", "",
              "| quantity | ref | " + " | ".join(runs) + " |",
              "|---|---|" + "---|" * len(runs)]
    for item in runs[next(iter(runs))]["items"]:
        if item["status"] != "graded":
            continue
        cells = []
        for g in grades:
            row = next(i for i in g["items"] if i["quantity"] == item["quantity"])
            cells.append(f"{row['got']:.6g} ({100 * row['rel_error']:+.2f} % "
                         f"{'PASS' if row['pass'] else 'FAIL'})")
        lines.append(f"| {item['quantity']} | {item['reference']:.6g} | "
                     + " | ".join(cells) + " |")
    lines += ["", "## Withdrawn criteria (measured, not graded)", "",
              "| quantity | reason |", "|---|---|"]
    for label, reason in sorted(WITHDRAWN.items()):
        lines.append(f"| {label} | {reason} |")
    lines += ["", "## Withdrawn numbers, for the record", "",
              "| quantity | " + " | ".join(runs) + " |",
              "|---|" + "---|" * len(runs)]
    for label in sorted(WITHDRAWN):
        cells = []
        for g in grades:
            row = next(i for i in g["items"] if i["quantity"] == label)
            cells.append(f"{row['got']:.6g} ({100 * row['rel_error']:+.2f} %)")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += ["", "## Verdict per grid", "",
              "| grid | dx | nsteps | graded | pass | mass drift | energy drift | "
              "troubled repairs |", "|---|---|---|---|---|---|---|---|"]
    for g in grades:
        budget = {i["quantity"]: i["got"] for i in g["items"]
                  if i["quantity"] in BUDGET_LABELS}
        mass = budget.get("mass_budget_drift")
        energy = budget.get("energy_budget_drift")
        fmt = lambda v: "n/a" if v is None else f"{v:.3e}"  # noqa: E731
        lines.append(f"| {g['grid'][0]}x{g['grid'][1]} | {g['dx']:.5f} | "
                     f"{g.get('nsteps')} | {g['verdict']['n_graded']} | "
                     f"{g['verdict']['n_graded_pass']} | {fmt(mass)} | {fmt(energy)} | "
                     f"{g.get('troubled_repairs')} |")
    if record:
        r = record[0]
        lines += ["", f"**Grid-of-record verdict: {r['verdict']['n_graded_pass']}/"
                      f"{r['verdict']['n_graded']} graded criteria inside "
                      f"{100 * TOL:.0f} %.**"]
    Path(args.md).write_text("\n".join(lines) + "\n")
    print(f"wrote {out} and {args.md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())