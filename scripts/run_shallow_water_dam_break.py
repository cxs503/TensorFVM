#!/usr/bin/env python3
"""Reproduce the Ritter/Stoker dam-break benchmark for TensorFVM's SWE solver.

One command produces every artefact quoted in
``docs/shallow-water-dam-break/REPORT.md``::

    PYTHONPATH=src python scripts/run_shallow_water_dam_break.py \
        --out src/tensorfvm/verification/artifacts/shallow-water-dam-break

Outputs (in ``--out``): ``metrics.json``, ``convergence.json``,
``exactness.json``, ``profile_<case>_n<n>.csv``, ``dam_break.png``,
``SUMMARY.md`` and ``manifest.json`` (versions, command line, thresholds).

Acceptance criterion (task statement): wave position and the still-water level
step within 5 % of the closed form at ``t* = 2``, waveform monotone.
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

from tensorfvm.shallow_water import (
    CASES,
    TOLERANCE,
    convergence_study,
    exactness_checks,
    figure_profiles_and_convergence,
    front_definition_study,
    run_case,
    sensitivity_study,
    write_artifacts,
)


def _fmt_error(value: float) -> str:
    return f"{100.0 * value:.3f} %"


def _summary_markdown(payload: dict) -> str:
    lines = ["# Ritter / Stoker dam-break benchmark — result summary", ""]
    lines.append(f"Generated by `scripts/run_shallow_water_dam_break.py` on "
                 f"{payload['meta']['generated_at']}.")
    lines.append("")
    lines.append(f"Acceptance threshold: every headline metric < {100 * TOLERANCE:.0f} % "
                 "relative error, waveform monotone (no spurious oscillation).")
    lines.append("")
    for key, run in payload["runs"].items():
        case = run["case"]
        disc = run["discretisation"]
        m = run["metrics"]
        lines.append(f"## {key}")
        lines.append("")
        lines.append(f"* h0 = {case['h0']} m, h1 = {case['h1']} m, g = {case['gravity']} m/s², "
                     f"t* = {disc['t_star_end']} (t = {disc['t_end']:.6f} s)")
        lines.append(f"* grid: n = {disc['n']}, dx = {disc['dx']:.6f} m "
                     f"({case['h0'] / disc['dx']:.0f} cells per h0), CFL = {disc['cfl']}, "
                     f"order = {disc['order']}, {disc['steps']} steps, "
                     f"{disc['wall_time_s']:.2f} s")
        lines.append(f"* reference: {case['reference']}")
        lines.append("")
        lines.append("| metric | reference (closed form) | TensorFVM (FVM) | relative error | < 5 % |")
        lines.append("|---|---|---|---|---|")
        rows = []
        if case["kind"] == "dry":
            # The published wave position is the *headline* estimator; the
            # wetted edge is quoted next to it, flagged, because it is a
            # depth-floor detector that does not converge under refinement
            # (see docs/verification-dam-break-front-metric/REPORT.md and
            # docs/case-fvm-dambreak-stoker/AUDIT.md).  Publishing only the
            # wetted edge -- which is what this summary used to do -- states a
            # grid-dependent floor as if it were a solution error.
            rows.append(("front position x_f (fan, headline) [m]", m["front_exact"],
                         m["front_fan"], m["front_fan_error"], "front_fan<5%"))
            rows.append(("front position x_f (wetted edge, diagnostic) [m]",
                         m["front_exact"], m["front_wetted"],
                         m["front_wetted_error"], "front_wetted<5%"))
        else:
            rows.append(("bore position x_s [m]", m["shock_exact"], m["shock_position"],
                         m["shock_error"], "shock_position<5%"))
            rows.append(("post-bore depth h2 [m]", m["h2_exact"], m["h2_measured"],
                         m["h2_error"], "plateau_h2<5%"))
            rows.append(("still-water step h2/h1 [-]",
                         m["step_ratio_exact"], m["step_ratio_measured"],
                         m["step_ratio_error"], "step_ratio<5%"))
        rows.append(("depth L1 error [-]", 0.0, m["depth_l1"], m["depth_l1"], "depth_l1<5%"))
        for label, ref, got, err, check in rows:
            mark = "✓" if run["verdict"][check]["pass"] else "✗"
            ref_s = "—" if label.startswith("depth L1") else f"{ref:.6f}"
            got_s = f"{got:.6f}" if not label.startswith("depth L1") else f"{got:.2e}"
            lines.append(f"| {label} | {ref_s} | {got_s} | {_fmt_error(err)} | {mark} |")
        lines.append("")
        series = m.get("front_series") or {}
        if series:
            lines.append(f"* wave position **series** x_f(t): graded samples "
                         f"{series['samples_graded']}/{series['samples']} "
                         f"(exact front must travel >= {series['min_cells']:g} cells); "
                         f"max relative error {_fmt_error(series['max_error'])} "
                         f"at t* = {series['max_error_t_star']:.3f}; "
                         f"pass {'yes' if series['pass'] else 'no'}")
            lines.append(f"* series samples not graded: {series['unresolved_samples']} "
                         f"({series['unresolved_undefined']} with an undefined headline "
                         f"estimator); their max error is "
                         f"{_fmt_error(series['unresolved_max_error']) if series['unresolved_max_error'] is not None else 'n/a'}")
            lines.append(f"* legacy estimator on the same series (NOT graded): max error "
                         f"{_fmt_error(series['legacy_max_error'])} at "
                         f"t* = {series['legacy_max_error_t_star']:.3f}")
        lines.append("")
        lines.append(f"* total variation TV(h) = {m['tv_numeric']:.6f} "
                     f"vs exact {m['tv_exact']:.6f} (ratio {m['tv_ratio']:.6f})")
        lines.append(f"* interior local extrema above {1e-4 * case['h0']:.1e} m: "
                     f"{m['local_extrema']} (monotone waveform)")
        lines.append(f"* mass drift {m['mass_drift']:.2e}, h_min = {m['h_min']:.3e} m, "
                     f"positivity clippings {disc['clipped_cells']}")
        lines.append(f"* all headline checks pass: "
                     f"**{'yes' if run['verdict']['all_pass'] else 'no'}**")
        lines.append("")
    lines.append("## Grid convergence")
    lines.append("")
    lines.append("| case | n | dx [m] | depth L1 | headline error | "
                 "x_f(t) series error | series graded | verdict failing |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for key, study in payload["studies"].items():
        for row in study["rows"]:
            headline = next(iter(row["headline"].values()))
            series = row.get("front_series")
            graded = row.get("front_series_graded")
            samples = row.get("front_series_samples")
            graded_cell = ("n/a" if graded is None else f"{graded}/{samples}")
            failing = row.get("verdict_failing")
            failing_cell = ("none" if failing == [] else
                            (", ".join(failing) if failing else "n/a"))
            lines.append(f"| {key} | {row['n']} | {row['dx']:.6f} | "
                         f"{row['depth_l1']:.3e} | {_fmt_error(headline)} | "
                         f"{_fmt_error(series)} | {graded_cell} | {failing_cell} |")
        lines.append("")
    lines.append("The ``x_f(t) series error`` column *is* the case acceptance "
                 "(whole transient vs the closed form, < 5 %); a grid that fails "
                 "it is listed under ``verdict failing`` rather than dropped.")
    lines.append("")
    if payload.get("front_definitions"):
        lines.append("## Dry-bed front definition study")
        lines.append("")
        lines.append("| n | wetted edge | level 1e-2 raw | level 1e-2 scaled |")
        lines.append("|---|---|---|---|")
        for row in payload["front_definitions"]["rows"]:
            lines.append(f"| {row['n']} | {_fmt_error(row['wetted_edge_error'])} | "
                         f"{_fmt_error(row['level_raw_error']['0.01'])} | "
                         f"{_fmt_error(row['level_scaled_error']['0.01'])} |")
        lines.append("")
    if payload.get("sensitivity"):
        lines.append("## Parameter sensitivity (n = %d)" % payload["sensitivity"]["rows"][0]["n"])
        lines.append("")
        lines.append("| variant | dry front err | wet bore err | wet step err | wet depth L1 | TV ratio | extrema |")
        lines.append("|---|---|---|---|---|---|---|")
        for row in payload["sensitivity"]["rows"]:
            lines.append(f"| {row['variant']} | {_fmt_error(row['dry_front_fan_error'])} | "
                         f"{_fmt_error(row['wet_shock_error'])} | "
                         f"{_fmt_error(row['wet_step_ratio_error'])} | "
                         f"{row['wet_depth_l1']:.3e} | {row['wet_tv_ratio']:.6f} | "
                         f"{row['wet_local_extrema']} |")
        lines.append("")
        lines.append(f"Worst headline error over all variants: "
                     f"{_fmt_error(payload['sensitivity']['worst_headline_error'])}.")
        lines.append("")
    lines.append("## Exact solutions certified without transcription")
    lines.append("")
    ex = payload["exactness"]
    lines.append(f"* Stoker Riemann invariant residual: "
                 f"{ex['stoker']['riemann_invariant_relative']:.3e} (relative)")
    lines.append(f"* Stoker mass jump residual: {ex['stoker']['mass_jump_relative']:.3e}")
    lines.append(f"* Stoker momentum jump residual: {ex['stoker']['momentum_jump_relative']:.3e}")
    lines.append(f"* Ritter depth at dam / h0: {ex['ritter']['h_at_dam_over_h0']:.12f} "
                 f"(exact 4/9), residual {ex['ritter']['h_at_dam_residual']:.3e}")
    lines.append(f"* Ritter fan mass vs h0 c0 t: relative {ex['ritter']['fan_mass_relative']:.3e}")
    lines.append("")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="src/tensorfvm/verification/artifacts/shallow-water-dam-break",
                        help="artefact directory")
    parser.add_argument("--n", type=int, default=1600, help="cells of the headline run")
    parser.add_argument("--cfl", type=float, default=0.4)
    parser.add_argument("--order", type=int, default=2)
    parser.add_argument("--t-star", type=float, default=2.0)
    parser.add_argument("--resolutions", default="100,200,400,800,1600",
                        help="comma-separated grid sizes of the convergence study")
    parser.add_argument("--skip-convergence", action="store_true")
    parser.add_argument("--skip-sensitivity", action="store_true")
    parser.add_argument("--skip-front-study", action="store_true")
    args = parser.parse_args(argv)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()

    print("== exactness checks (closed forms re-derived, no tabulated values) ==")
    exactness = exactness_checks()
    print(f"   Stoker momentum jump residual : "
          f"{exactness['stoker']['momentum_jump_relative']:.3e}")
    print(f"   Ritter fan mass residual      : "
          f"{exactness['ritter']['fan_mass_relative']:.3e}")
    print(f"   Stoker states h0={exactness['stoker_h0_h1'][0]} "
          f"h1={exactness['stoker_h0_h1'][1]}: h2={exactness['stoker_state']['h2']:.9f} m, "
          f"u2={exactness['stoker_state']['u2']:.9f} m/s, "
          f"U={exactness['stoker_state']['shock_speed']:.9f} m/s")

    print(f"\n== headline runs (n = {args.n}, CFL = {args.cfl}, order = {args.order}, "
          f"t* = {args.t_star:g}) ==")
    runs = {}
    for key, case in CASES.items():
        run = run_case(case, n=args.n, cfl=args.cfl, order=args.order,
                       t_star=args.t_star)
        runs[key] = run
        m, disc = run["metrics"], run["discretisation"]
        print(f"\n   [{key}] n={disc['n']} dx={disc['dx']:.5f} m steps={disc['steps']} "
              f"({disc['wall_time_s']:.2f} s)")
        if case.kind == "dry":
            print(f"     front   exact {m['front_exact']:.6f} m  "
                  f"FVM {m['front_fan']:.6f} m (fan)  "
                  f"error {_fmt_error(m['front_fan_error'])}  "
                  f"[{'PASS' if run['verdict']['front_fan<5%']['pass'] else 'FAIL'}]")
            print(f"     front   wetted edge {m['front_wetted']:.6f} m  "
                  f"error {_fmt_error(m['front_wetted_error'])}  "
                  f"(diagnostic only: depth-floor detector, non-convergent)")
        else:
            print(f"     bore    exact {m['shock_exact']:.6f} m  "
                  f"FVM {m['shock_position']:.6f} m  "
                  f"error {_fmt_error(m['shock_error'])}  "
                  f"[{'PASS' if run['verdict']['shock_position<5%']['pass'] else 'FAIL'}]")
            print(f"     h2      exact {m['h2_exact']:.6f} m  FVM {m['h2_measured']:.6f} m  "
                  f"error {_fmt_error(m['h2_error'])}")
            print(f"     h2/h1   exact {m['step_ratio_exact']:.6f}  "
                  f"FVM {m['step_ratio_measured']:.6f}  "
                  f"error {_fmt_error(m['step_ratio_error'])}  "
                  f"[{'PASS' if run['verdict']['step_ratio<5%']['pass'] else 'FAIL'}]")
        print(f"     depth L1 {m['depth_l1']:.3e}  TV ratio {m['tv_ratio']:.6f}  "
              f"extrema {m['local_extrema']}  mass drift {m['mass_drift']:.1e}")
        series = m.get("front_series") or {}
        if series:
            print(f"     series  x_f(t) max error {_fmt_error(series['max_error'])} at "
                  f"t*={series['max_error_t_star']:.3f} over "
                  f"{series['samples_graded']}/{series['samples']} graded samples "
                  f"[{'PASS' if series['pass'] else 'FAIL'}]"
                  f"  (legacy estimator on the same series: "
                  f"{_fmt_error(series['legacy_max_error'])})")
        print(f"     verdict: {'ALL PASS' if run['verdict']['all_pass'] else 'FAILED'}")

    studies = {}
    if not args.skip_convergence:
        resolutions = tuple(int(v) for v in args.resolutions.split(",") if v.strip())
        print("\n== grid convergence (depth L1 and headline error) ==")
        for key, case in CASES.items():
            study = convergence_study(case, resolutions=resolutions, cfl=args.cfl,
                                     order=args.order)
            studies[key] = study
            for row in study["rows"]:
                headline = next(iter(row["headline"].values()))
                print(f"   {key:12s} n={row['n']:5d} dx={row['dx']:.6f} "
                      f"L1={row['depth_l1']:.3e} headline={_fmt_error(headline)} "
                      f"TV={row['tv_ratio']:.6f}")
            print(f"   {key:12s} observed order of depth L1: "
                  f"{study['observed_order_l1']:.2f}")

    sensitivity = {}
    if not args.skip_sensitivity:
        print("\n== parameter sensitivity (n = 800) ==")
        sensitivity = sensitivity_study(n=800)
        for row in sensitivity["rows"]:
            print(f"   {row['variant']:10s} dry_front={_fmt_error(row['dry_front_fan_error'])} "
                  f"wet_bore={_fmt_error(row['wet_shock_error'])} "
                  f"wet_step={_fmt_error(row['wet_step_ratio_error'])} "
                  f"wet_L1={row['wet_depth_l1']:.3e} extrema={row['wet_local_extrema']}")
        print(f"   worst headline error {_fmt_error(sensitivity['worst_headline_error'])} "
              f"(tolerance {100 * TOLERANCE:.0f} %)")

    front_study = {}
    if not args.skip_front_study:
        print("\n== dry-bed front definition study (cusp smear sensitivity) ==")
        front_study = front_definition_study()
        for row in front_study["rows"]:
            print(f"   n={row['n']:5d} wetted_edge={_fmt_error(row['wetted_edge_error'])} "
                  f"level(1e-2) raw={_fmt_error(row['level_raw_error']['0.01'])} "
                  f"scaled={_fmt_error(row['level_scaled_error']['0.01'])}")

    figure_path = out / "dam_break.png"
    figure_profiles_and_convergence(runs, studies, figure_path, t_star=args.t_star)

    payload = {
        "meta": {
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "tolerance": TOLERANCE,
            "t_star": args.t_star,
            "python": sys.version.split()[0],
            "numpy": np.__version__,
            "platform": platform.platform(),
            "git_commit": _git_commit(),
            "command": "PYTHONPATH=src python scripts/run_shallow_water_dam_break.py "
                       + " ".join(sys.argv[1:]),
            "wall_time_s": None,
        },
        "exactness": exactness,
        "runs": runs,
        "studies": studies,
        "sensitivity": sensitivity,
        "front_definitions": front_study,
        "profiles": {},
    }
    written = write_artifacts(out, payload)
    payload["meta"]["wall_time_s"] = time.perf_counter() - started

    if sensitivity:
        sens_path = out / "sensitivity.json"
        sens_path.write_text(json.dumps(sensitivity, indent=2) + "\n")
        written["sensitivity.json"] = str(sens_path)

    if front_study:
        fd_path = out / "front_definitions.json"
        fd_path.write_text(json.dumps(front_study, indent=2) + "\n")
        written["front_definitions.json"] = str(fd_path)

    summary_path = out / "SUMMARY.md"
    summary_path.write_text(_summary_markdown(payload))
    written["SUMMARY.md"] = str(summary_path)

    manifest = {
        "meta": payload["meta"],
        "artifacts": {name: str(Path(name).name) for name in written},
        "cases": {key: run["case"] for key, run in runs.items()},
        "verdict": {key: run["verdict"] for key, run in runs.items()},
    }
    manifest_path = out / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"\nartefacts written to {out}/ : {len(written) + 1} files")
    print(f"   {summary_path}")
    ok = all(run["verdict"]["all_pass"] for run in runs.values())
    print(f"\nOVERALL: {'ALL HEADLINE METRICS WITHIN 5%' if ok else 'METRIC OUT OF TOLERANCE'}")
    return 0 if ok else 1


def _git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"],
                                       text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return "unknown"


if __name__ == "__main__":
    raise SystemExit(main())