"""Audit ``native_sections3d`` exact sections and emit the evidence bundle.

Reproduce: ``python3 scripts/audit_native_sections.py``
Writes (all numbers below are produced here, none hand-copied):

* ``docs/verification-native-sections/results.json``  - every audited case
* ``docs/verification-native-sections/table.md``      - markdown tables from the JSON
* ``docs/verification-native-sections/section-rings.png``   - the stitched polygons
* ``docs/verification-native-sections/ring-deficit.png``    - measured vs analytic deficit

Exit code is non-zero if any published claim fails, so the bundle cannot be
regenerated green over a failure.
"""
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib                                                  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt                                     # noqa: E402
from matplotlib.collections import PolyCollection                    # noqa: E402

from tensorfvm.verification import native_sections as vs            # noqa: E402

OUT = ROOT / "docs" / "verification-native-sections"
OUT.mkdir(parents=True, exist_ok=True)

record = vs.section_study()
(OUT / "results.json").write_text(json.dumps(record, indent=1, sort_keys=True) + "\n")

rows = record["cases"]["box_mid_plane"]
ring = record["cases"]["annulus_rings"]
claims = record["claims"]

table = ["<!-- generated by scripts/audit_native_sections.py, do not edit -->", "",
         "### Box sections, plane z = 0.5 (closed form: area 1)", "",
         "| n | coincident w/ grid plane | polygons | expected | polygon sum | unique area | error |",
         "|---:|---|---:|---:|---:|---:|---:|"]
for r in rows:
    table.append("| {n} | {coincident_interior_plane} | {n_polygons} | {n_polygons_expected} | "
                 "{polygon_sum_area:.15f} | {unique_area:.15f} | {err:.2e} |".format(
                     err=abs(r["unique_area"] - 1.0), **r))
table += ["", "### Concentric O-grid rings (R = 1, r = 0.5, z = 0.1)", "",
          "| n | polygons | section area | closed form | rel err | vs pi | analytic sin(t)/t-1 | hull + |",
          "|---:|---:|---:|---:|---:|---:|---:|---:|"]
for r in ring:
    table.append("| {n_theta} | {n_polygons} | {section_area:.12f} | {closed_form_area:.12f} | "
                 "{rel_error_vs_closed_form:.2e} | {rel_error_vs_pi:+.6f} | "
                 "{analytic_sin_over_t_minus_one:+.6f} | {hull_rel_overestimate:+.4f} |".format(**r))
table += ["", "### Claim ledger", "", "| claim | value |", "|---|---|"]
for k, v in claims.items():
    table.append(f"| `{k}` | `{v}` |")
(OUT / "table.md").write_text("\n".join(table) + "\n")

# figure 1: the stitched rings, n = 24
mesh = vs.annulus_mesh(24)
polygons, _, _ = vs.section_areas(mesh, value=0.1)
fig, ax = plt.subplots(figsize=(4.8, 4.8), constrained_layout=True)
ax.add_collection(PolyCollection(polygons, facecolors="none", edgecolors="C0", linewidths=0.6))
theta = 2 * np.pi * np.arange(200) / 200
ax.plot(np.cos(theta), np.sin(theta), "k--", lw=1.0, label="R = 1 (analytic)")
ax.plot(0.5 * np.cos(theta), 0.5 * np.sin(theta), "k:", lw=1.0, label="r = 0.5 (analytic)")
ax.set_aspect("equal")
ax.set(xlabel="x", ylabel="y",
       title=f"native_sections3d rings, n_theta = 24, {len(polygons)} polygons")
ax.legend(fontsize=7)
fig.savefig(OUT / "section-rings.png", dpi=110)
plt.close(fig)

# figure 2: measured deficit vs analytic sin(t)/t - 1
ns = np.array([r["n_theta"] for r in ring])
measured = np.array([r["rel_error_vs_pi"] for r in ring])
analytic = np.array([r["analytic_sin_over_t_minus_one"] for r in ring])
fig, ax = plt.subplots(figsize=(5.4, 3.6), constrained_layout=True)
ax.loglog(ns, -measured, "o-", label="measured section / pi(R^2-r^2) - 1")
ax.loglog(ns, -analytic, "k--", lw=1.0, label="analytic sin(2pi/n)/(2pi/n) - 1")
ax.loglog(ns, -analytic[-1] * (ns / ns[-1]) ** -2, ":", color="gray", label="O(h^2) slope")
ax.set(xlabel="n_theta", ylabel="relative deficit")
ax.set_title("ring section deficit tracks the analytic quadrature deficit")
ax.grid(True, which="both", alpha=.3)
ax.legend(fontsize=7)
fig.savefig(OUT / "ring-deficit.png", dpi=110)
plt.close(fig)

failures = []
if not claims["box_unique_area_max_error"] < 1e-14:
    failures.append("box unique area")
if not claims["box_polygon_count_matches_semantics"]:
    failures.append("box polygon count")
if not claims["ring_closed_form_max_rel_error"] < 1e-13:
    failures.append("ring closed form")
if not claims["ring_deficit_tracks_analytic"] < 1e-13:
    failures.append("ring deficit analytic")
if not claims["tangency_dropped"]:
    failures.append("tangency")
if not claims["outside_plane_empty"]:
    failures.append("outside plane")
if not claims["hull_control_rel_overestimate"] > 0.33:
    failures.append("hull control")
print(json.dumps({"claims": claims, "failures": failures}, indent=1))
raise SystemExit(1 if failures else 0)
