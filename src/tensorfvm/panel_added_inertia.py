"""Rotational added inertia (``M_44..M_66``) from the source-panel solver.

Why this module exists
----------------------
:mod:`tensorfvm.panel_added_mass` measures the *translational* added mass
``M_ij`` of a closed body in an unbounded ideal fluid and verifies it against
the exact Lamb ellipsoid factors.  :mod:`tensorfvm.maneuvering.dynamics` needs
the rotational block as well -- the roll/pitch/yaw inertia used to integrate the
manoeuvring equations -- and until now that block was a slender-body
placeholder with no first-principles value to compare against
(``docs/VERIFICATION_DEBT_LEDGER.md`` item D1).

The generalised-coordinate formulation makes the extension a one-line change of
the surface velocity field.  For a body with generalised velocity ``q_j`` whose
rigid-body surface velocity is ``V_j(x)``, the fluid kinetic energy is

    T = 1/2 (M_ij) q_i q_j,      M_ij = -rho * integral_S phi_i (V_j . n) dS,   (1)

where ``phi_i`` solves the Neumann problem

    laplace(phi_i) = 0,   dphi_i/dn = -(V_i . n) on S,   phi_i -> 0 at infinity, (2)

and ``n`` points into the fluid (outward from the body; the same convention as
:mod:`tensorfvm.panel_potential`).  Translation uses ``V_i = e_i`` (which is what
:mod:`tensorfvm.panel_added_mass` does); rotation about the axis ``e_i`` through
the point ``x0`` uses ``V_i(x) = e_i x (x - x0)``.  Equation (2) with a spatially
varying right-hand side is exactly what :func:`panel_potential.solve_sources`
accepts already (``U`` may be an ``(n_panels, 3)`` array), so the discretisation,
quadrature and image machinery are shared with the verified translational route.

Exact anchors
-------------
1. **Sphere, any axis** -- ``(Omega x (x - x0)) . n = 0`` identically on a sphere
   centred at ``x0`` (rotation is tangential there), so ``phi = 0`` solves (2)
   and ``M = 0``.  The rotational added inertia of a sphere in an ideal fluid is
   *exactly zero*; a non-zero panel value is pure discretisation error and must
   vanish under refinement.  (This also corrects the anchor quoted in the
   verification-debt ledger, which claimed ``(5/8) pi rho a^5`` for a sphere;
   see ``docs/verification-added-inertia-panel/REPORT.md``.)
2. **Body of revolution, symmetry axis** -- the same argument applies: the
   surface is generated by revolving a profile, so the rotation velocity is
   everywhere tangent to the surface and ``M`` about that axis is exactly zero.
   For a spheroid this is the classical ``K_11 = 0`` entry of Lamb's tables.
3. **Spheroid, transverse axis** -- the only non-trivial exact value.  Lamb
   (1932, §114) gives, for a prolate spheroid ``a > b = c``,

       I_perp = (1/5) rho V (b^2 - a^2)^2 (beta0 - alpha0)
                / [ 2 (b^2 - a^2) + (b^2 + a^2) (beta0 - alpha0) ],             (3)

   with the Lamb integrals ``alpha0, beta0`` of
   :func:`tensorfvm.panel_added_mass.lamb_ellipsoid_factors`.  Limits: sphere
   ``a = b`` gives ``0`` (consistent with anchor 1); ``a >> b`` gives
   ``I_perp -> (1/15) rho V a^2``.  Equation (3) is implemented as
   :func:`lamb_rotational_inertia` and used purely as a *literature* comparison
   -- the panel value is computed independently.

References
----------
* Lamb, H. (1932) *Hydrodynamics*, 6th ed., §108-114.
* Landau & Lifshitz (1987) *Fluid Mechanics*, §11.
* Newman, J.N. (1977) *Marine Hydrodynamics*, §4.4.
* Hess, J.L. & Smith, A.M.O. (1964) *Progress in Aeronautical Sciences* 8, 1-138.
"""

from __future__ import annotations

import numpy as np

from .panel_added_mass import lamb_ellipsoid_factors, source_potential
from .panel_potential import IMAGE_SPECS, solve_sources
from .twin_hull_geometry import PanelSet

__all__ = [
    "lamb_rotational_inertia",
    "rigid_rotation_field",
    "rotational_added_inertia",
    "rotation_momentum_residual",
]


def rigid_rotation_field(points: np.ndarray, axis: int, origin=None) -> np.ndarray:
    """Surface velocity field ``V = e_axis x (x - x0)`` of unit angular velocity."""
    pts = np.atleast_2d(np.asarray(points, dtype=float))
    o = np.zeros(3) if origin is None else np.asarray(origin, dtype=float)
    if o.shape != (3,):
        raise ValueError("origin must be a 3-vector")
    r = pts - o
    out = np.empty_like(r)
    # e_axis x r  with e_axis = e_k  ->  cyclic permutation with a sign flip
    out[:, (axis + 1) % 3] = -r[:, (axis + 2) % 3]
    out[:, (axis + 2) % 3] = r[:, (axis + 1) % 3]
    out[:, axis] = 0.0
    return out


def rotational_added_inertia(panels: PanelSet, *, rho: float = 1.0, order: int = 3,
                             axes: tuple[int, ...] = (0, 1, 2), origin=None,
                             images=IMAGE_SPECS["body"]) -> np.ndarray:
    """Rotational added-inertia tensor ``I_ij`` (equation 1) of a closed body.

    ``axes`` selects which rows/columns are filled; the rest stay zero.
    ``origin`` is the centre of rotation (default: the coordinate origin, which
    is where the spheroid/sphere panelisations are centred).  The sign
    convention matches :func:`tensorfvm.panel_added_mass.added_mass_matrix`, so
    a closed body gives ``I_ii >= 0``.
    """
    if rho <= 0.0:
        raise ValueError("rho must be positive")
    if panels.n_panels == 0:  # pragma: no cover - defensive
        raise ValueError("empty panel set")
    out = np.zeros((3, 3))
    areas = panels.areas
    for i in axes:
        V = rigid_rotation_field(panels.centroids, i, origin)
        sigma = solve_sources(panels, V, order=order, images=images)
        phi = source_potential(panels.centroids, sigma, panels, order=order, images=images)
        for j in axes:
            Vj = rigid_rotation_field(panels.centroids, j, origin)
            out[i, j] = -rho * float(np.sum(phi * np.einsum("ij,ij->i", Vj, panels.normals) * areas))
    if len(axes) == 3:
        out = 0.5 * (out + out.T)
    return out


def rotation_momentum_residual(panels: PanelSet, omega: np.ndarray, sigma: np.ndarray, *,
                               order: int = 2, images=IMAGE_SPECS["body"],
                               origin=None) -> float:
    """max |V . n| on the active panels, non-dimensionalised by |Omega| * R.

    Checks that the source strengths returned for a rotation mode really satisfy
    the impermeability condition (2) at the body surface.  ``R`` is the largest
    centroid distance from the centre of rotation, so the residual is a relative
    measure comparable across meshes.
    """
    from .panel_potential import induced_velocity

    o = np.zeros(3) if origin is None else np.asarray(origin, dtype=float)
    om = np.asarray(omega, dtype=float)
    om = om / np.linalg.norm(om)
    mask = panels.active_mask()
    V = np.cross(np.broadcast_to(om, (panels.n_panels, 3)), panels.centroids - o)
    v = V[mask] + induced_velocity(panels.centroids[mask], sigma, panels, order=order,
                                   images=images)
    vn = np.einsum("ij,ij->i", v, panels.normals[mask]) + 0.5 * sigma[mask]
    scale = float(np.linalg.norm(om) * np.max(np.linalg.norm(panels.centroids - o, axis=1)))
    return float(np.abs(vn).max() / scale)


def lamb_rotational_inertia(a: float, b: float, c: float | None = None,
                            *, rho: float = 1.0) -> np.ndarray:
    """Exact ``3x3`` rotational added inertia of an ellipsoid (Lamb, equation 3).

    ``a, b, c`` are the semi-axes; ``c`` defaults to ``b`` (spheroid about x).
    Axis ``i`` uses the two other semi-axes, so all three diagonal entries are
    returned and the off-diagonal entries are zero by the ellipsoid's symmetry.
    """
    if c is None:
        c = b
    axes = np.array([a, b, c], dtype=float)
    if np.any(axes <= 0.0):
        raise ValueError("ellipsoid semi-axes must be positive")
    if rho <= 0.0:
        raise ValueError("rho must be positive")
    a0, b0, c0 = lamb_ellipsoid_factors(a, b, c)
    lamps = np.array([a0, b0, c0])
    vol = 4.0 / 3.0 * np.pi * a * b * c
    out = np.zeros((3, 3))
    for i in range(3):
        j, k = (i + 1) % 3, (i + 2) % 3
        dj = axes[j] ** 2 - axes[k] ** 2
        dl = lamps[j] - lamps[k]
        den = 2.0 * dj + (axes[j] ** 2 + axes[k] ** 2) * dl
        if abs(den) < 1e-300:  # pragma: no cover - only the exact sphere limit
            out[i, i] = 0.0
            continue
        out[i, i] = -0.2 * rho * vol * dj * dj * dl / den
    return out