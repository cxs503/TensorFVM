def summarise(result):
    """Human-readable one-liners for the blocking findings."""
    lines = []
    for item in result['blocking']:
        if item['kind'] == 'artifact':
            lines.append(
                f"{item['field']}: the canonical artifact does not record the "
                f"Re_tau it was solved at (gate fell back to {item['resolved']})")
        elif item['kind'] == 'number':
            lines.append(
                f"{item['field']}: quoted {item['quoted']} "
                f"({item['status']}); canonical vintage {result['canonical_re_tau']} "
                f"gives {item['resolved']}; matched vintages {item['matching_vintages']}")
        else:
            lines.append(
                f"text[{item['field']}] {item['token']}% ({item['status']}) "
                f"in: ...{item['context'].strip()}...")
    return lines