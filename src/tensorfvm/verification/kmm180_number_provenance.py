"""Number-provenance gate for ``CASE-FVM-CHANNEL-KMM180``.

Why this module exists
----------------------
The case publishes a catalog entry
(``docs/oss_solutions/CASE-FVM-CHANNEL-KMM180.json``) whose ``repro_cmd`` is

    python -m tensorfvm.benchmark_channel_kmm1987 --out docs/case-fvm-channel-kmm180

The catalog and the artifacts, however, are produced by *different* entry points,
and those entry points do **not** solve the same discrete problem: the case
driver solves at the nominal ``Re_tau = 180`` while the window audit
(``tensorfvm.verification.kmm180_windows.audit``) solves at the reference
``Re_tau = 182.088``.  Both write a record labelled ``(model, n)``, so a quoted
decimal such as ``0.03456`` is reproducible by one artifact and not the other,
and nothing in the bundle says which.  A number that cannot be traced to the
artifact the reproducer runs is not verifiable, however small the difference is.

This module makes that traceability machine-checkable:

* every published decimal in the catalog is parsed with
  :class:`decimal.Decimal`, so the *quoted precision* (3 decimals vs 5) survives
  parsing instead of being lost in a ``float``;
* every machine-written artifact record is indexed by the key that decides the
  number: ``(quantity, model, n, window)`` **plus the Re_tau the record was
  solved at** -- the key the bundle used to omit;
* a claim passes only when it is reproduced by a record of the *canonical*
  vintage, i.e. the ``Re_tau`` the catalog's own ``repro_cmd`` produces.  A
  claim that only a different vintage reproduces is reported as
  ``SNAPSHOT_ONLY``: the value may be correct for the problem that vintage
  solved, but the catalog then advertises a number its reproducer cannot make;
* free-text percentages in the catalog prose are scanned under the same rule,
  because prose is where a superseded vintage survives longest.

Nothing here re-grades a solution: the module reads published artifacts and the
catalog only, so it cannot launder a verdict.  It answers exactly one question
-- *can every published number be regenerated by the command the entry tells you
to run?*

Usage
-----
::

    PYTHONPATH=src python scripts/audit_case_fvm_channel_kmm180_provenance.py --check
    PYTHONPATH=src python scripts/audit_case_fvm_channel_kmm180_provenance.py --repair
    PYTHONPATH=src python scripts/audit_case_fvm_channel_kmm180_provenance.py --write
"""
from __future__ import annotations

import json
import re
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CATALOG = ROOT / 'docs' / 'oss_solutions' / 'CASE-FVM-CHANNEL-KMM180.json'
CASE_DIR = ROOT / 'docs' / 'case-fvm-channel-kmm180'

#: Quantities the gate compares.  ``window`` is ``None`` for solution-level
#: scalars (they do not depend on a grading window).
QUANTITIES = ('rms_relative', 'cells', 'verdict', 'cf_relative_error',
              'bulk_relative_error')

#: Window labels used by the extractors below.  A window is identified by its
#: *name* only when the name fixes the interval (``legacy_full`` always means
#: ``30 <= y+ <= max reference y+``; ``log_layer`` always means
#: ``30 <= y+ <= 0.2 Re_tau``).  An artifact that uses a different upper bound
#: gets its own label, so it can never be matched against a claim by accident.
LEGACY = 'legacy_full'
LOG_LAYER = 'log_layer'


# --------------------------------------------------------------------------- #
# Artifact registry
# --------------------------------------------------------------------------- #

def _record(quantity, value, *, model=None, n=None, re_tau=None, window=None,
            norm='rms_rel_unweighted', source='', verifier=None):
    return dict(quantity=quantity, value=value, model=model, n=n,
                re_tau=(None if re_tau is None else float(re_tau)),
                window=window, norm=norm, source=source, verifier=verifier)


def _from_benchmark(path):
    """Canonical case artifact (``benchmark.json``, solved at nominal Re_tau)."""
    data = json.loads(path.read_text())
    out = []
    re_tau = _artifact_nominal_re_tau(data)
    for case in data['cases']:
        model, n = case['model'], case['n']
        for name in (LEGACY, LOG_LAYER):
            block = case[name]
            for quantity, key in (('rms_relative', 'rms_relative'),
                                  ('cells', 'cells'),
                                  ('verdict', 'verdict')):
                out.append(_record(quantity, block[key], model=model, n=n,
                                   re_tau=re_tau, window=name,
                                   source=f'{path.parent.name}/benchmark.json',
                                   verifier=path.name))
        for quantity in ('cf_relative_error', 'bulk_relative_error'):
            out.append(_record(quantity, case[quantity], model=model, n=n,
                               re_tau=re_tau,
                               source=f'{path.parent.name}/benchmark.json',
                               verifier=path.name))
    return out


def _from_window_audit(path):
    """``kmm180_windows`` audit: same labels, different Re_tau (the reference's)."""
    data = json.loads(path.read_text())
    re_tau = data['reference']['re_tau']
    out = []
    for case in data['cases']:
        model, n = case['model'], case['cells']
        for name, key in ((LEGACY, 'full'), (LOG_LAYER, '0.20')):
            block = case['windows'][key]
            out.append(_record('rms_relative', block['rms_relative'], model=model,
                               n=n, re_tau=re_tau, window=name,
                               source='verification-channel-kmm180/summary.json',
                               verifier='kmm180_windows.audit'))
            out.append(_record('cells', block['cells'], model=model, n=n,
                               re_tau=re_tau, window=name,
                               source='verification-channel-kmm180/summary.json',
                               verifier='kmm180_windows.audit'))
    return out


def _from_metric_norm(path):
    """Four norms per window; the unweighted RMS is the catalog's quantity."""
    data = json.loads(path.read_text())
    out = []
    re_tau = _artifact_nominal_re_tau(data)
    for case in data['cases']:
        model, n = case['model'], case['n']
        for name in (LEGACY, LOG_LAYER):
            block = case[name]
            for norm, value in block['values'].items():
                out.append(_record('rms_relative', value, model=model, n=n,
                                   re_tau=re_tau, window=name, norm=norm,
                                   source='verification-channel-kmm180-metric-norm/summary.json',
                                   verifier='kmm180_metric_norm.audit'))
            out.append(_record('cells', block['window']['cells'], model=model, n=n,
                               re_tau=re_tau, window=name,
                               source='verification-channel-kmm180-metric-norm/summary.json',
                               verifier='kmm180_metric_norm.audit'))
    return out


def _from_direct_anchor(path):
    """Two vintages in one file: ``anchor`` (MKM1999, 178.12) and ``proxy``."""
    data = json.loads(path.read_text())
    out = []
    for case in data['cases']:
        model, n = case['model'], case['n']
        for vintage in ('anchor', 'proxy'):
            block = case[vintage]
            re_tau = block['re_tau']
            for name, key in ((LEGACY, 'full'), (LOG_LAYER, 'log_layer')):
                entry = block[key]
                verifier = f'kmm180_direct_anchor.{vintage}'
                source = 'verification-channel-kmm180-direct-anchor/summary.json'
                # An ungradable window carries a reason and no RMS; it is still
                # a record (a claim quoting a value there has no provenance).
                for quantity in ('rms_relative', 'cells', 'verdict'):
                    if quantity in entry:
                        out.append(_record(quantity, entry[quantity], model=model,
                                           n=n, re_tau=re_tau, window=name,
                                           source=source, verifier=verifier))
    return out


def _from_refband(path):
    """Reference-band audit; its log-layer window is ``30 <= y+ <= 36``."""
    data = json.loads(path.read_text())
    refs = data['references']
    out = []
    for key, case in data['cases'].items():
        model, n = case['model'], case['n']
        for ref, entry in case['per_reference'].items():
            out.append(_record('rms_relative', entry['rms'], model=model, n=n,
                               re_tau=refs[ref]['re_tau'],
                               window='refband_log_layer',
                               source='case-fvm-channel-kmm180-refband/summary.json',
                               verifier=f'kmm180_refband[{ref}]'))
    return out


EXTRACTORS = (
    ('case-fvm-channel-kmm180/benchmark.json', _from_benchmark, True),
    ('verification-channel-kmm180/summary.json', _from_window_audit, False),
    ('verification-channel-kmm180-metric-norm/summary.json', _from_metric_norm, False),
    ('verification-channel-kmm180-direct-anchor/summary.json', _from_direct_anchor, False),
    ('case-fvm-channel-kmm180-refband/summary.json', _from_refband, False),
)


def _driver_nominal_re_tau():
    """The nominal Re_tau the case driver solves at (its declared default)."""
    import inspect
    from .. import benchmark_channel_kmm1987 as driver
    return float(inspect.signature(driver.run_case).parameters['re_tau'].default)


def _artifact_nominal_re_tau(data):
    """Re_tau the canonical artifact was solved at.

    The committed artifact did not record it, so fall back to the driver's
    default -- and report that fallback, because an artifact that does not name
    the Re_tau it solved makes every "(model, n)" label in the bundle ambiguous
    between the nominal and the reference Reynolds number.  ``repair`` writes the
    field so the fallback stops being needed.
    """
    if 'nominal_re_tau' in data:
        return float(data['nominal_re_tau'])
    return _driver_nominal_re_tau()


def canonical_re_tau():
    """The Re_tau the catalog's own ``repro_cmd`` solves at.

    Read from the canonical artifact, never hard-coded: if the driver changes
    its nominal Re_tau the gate follows it instead of silently passing.
    """
    return _artifact_nominal_re_tau(json.loads((CASE_DIR / 'benchmark.json').read_text()))


def load_records(root=None):
    """Load every indexed artifact record.  Missing artifacts are skipped."""
    root = ROOT if root is None else Path(root)
    records, present = [], []
    for rel, extractor, canonical in EXTRACTORS:
        path = root / 'docs' / rel
        if not path.is_file():
            continue
        present.append((rel, canonical))
        records.extend(extractor(path))
    if not present:
        raise FileNotFoundError('no KMM180 artifacts found')
    return records, present


# --------------------------------------------------------------------------- #
# Claims: the published decimals
# --------------------------------------------------------------------------- #

def load_catalog(path=None):
    """Parse the catalog keeping the quoted precision of every number."""
    path = CATALOG if path is None else Path(path)
    text = path.read_text()
    return json.loads(text, parse_float=Decimal, parse_int=Decimal), text


def _claim(quantity, quoted, *, model, n, window, field, source='catalog'):
    return dict(quantity=quantity, quoted=quoted, model=model, n=int(n),
                window=window, field=field, source=source)


def catalog_claims(catalog):
    """Every graded decimal the catalog publishes, as comparable claims."""
    claims = []

    windows = catalog.get('grading_windows', {})
    for name in (LEGACY, LOG_LAYER):
        block = windows.get(name)
        if not block:
            continue
        if 'cells_n256' in block:
            claims.append(_claim('cells', block['cells_n256'], model='sst', n=256,
                                 window=name, field=f'grading_windows.{name}.cells_n256'))
        if 'sst_rms_relative' in block:
            claims.append(_claim('rms_relative', block['sst_rms_relative'],
                                 model='sst', n=256, window=name,
                                 field=f'grading_windows.{name}.sst_rms_relative'))
        if 'sst_verdict' in block:
            claims.append(_claim('verdict', block['sst_verdict'], model='sst', n=256,
                                 window=name,
                                 field=f'grading_windows.{name}.sst_verdict'))

    per_window = {'log_rms_legacy': (LEGACY, 'rms_relative'),
                  'log_rms_log_layer': (LOG_LAYER, 'rms_relative'),
                  'verdict_legacy': (LEGACY, 'verdict'),
                  'verdict_log_layer': (LOG_LAYER, 'verdict')}
    per_case = {'cf_error': 'cf_relative_error',
                'bulk_u_plus_error': 'bulk_relative_error'}
    for case, fields in catalog.get('key_results', {}).items():
        match = re.fullmatch(r'(?P<model>[a-z]+)_n(?P<n>\d+)', case)
        if not match:
            raise ValueError(f'key_results entry {case!r} does not parse as <model>_n<n>')
        model, n = match.group('model'), int(match.group('n'))
        for field, value in fields.items():
            if field in per_window:
                window, quantity = per_window[field]
                claims.append(_claim(quantity, value, model=model, n=n,
                                     window=window, field=f'key_results.{case}.{field}'))
            elif field in per_case:
                claims.append(_claim(per_case[field], value, model=model, n=n,
                                     window=None,
                                     field=f'key_results.{case}.{field}'))
    return claims


#: Catalog string fields scanned for free-text percentages.
#: Only the fields whose percentages are *graded errors* are scanned.  Prose
#: that quotes mechanism diagnostics (implied kappa agreement, momentum-flux
#: residuals) is sourced from its own audits -- ``verification-channel-kmm180-
#: loglaw``, ``-budget`` -- where those numbers are gated against the artifact
#: that computes them; scanning them here would flag a correctly-cited number
#: for having the wrong provenance path.  The limitation is stated in the report.
TEXT_FIELDS = ('summary', 'verdict', 'notes', 'dns_proxy')

_PERCENT = re.compile(r'(?<![\d.])(\d+(?:\.\d+)?)\s*%')


def _dig(data, dotted):
    node = data
    for part in dotted.split('.'):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def text_claims(catalog):
    """Percentages quoted in the catalog prose, with the precision they carry."""
    out = []
    for field in TEXT_FIELDS:
        text = _dig(catalog, field)
        if not isinstance(text, str):
            continue
        for match in _PERCENT.finditer(text):
            token = match.group(1)
            decimals = len(token.split('.')[1]) if '.' in token else 0
            out.append(dict(field=field, token=token,
                            quoted=Decimal(token), decimals=decimals,
                            context=text[max(0, match.start() - 45):match.end() + 15]))
    return out


# --------------------------------------------------------------------------- #
# Matching
# --------------------------------------------------------------------------- #

def _rounds_to(value, quoted):
    """Does ``value`` reproduce ``quoted`` at the precision ``quoted`` carries?"""
    if isinstance(quoted, Decimal):
        exponent = quoted.as_tuple().exponent
        if exponent >= 0:
            return abs(Decimal(str(value)) - quoted) < Decimal('1e-9')
        step = Decimal(1).scaleb(exponent)
        return abs(Decimal(repr(float(value))) - quoted) <= step / 2 + Decimal('1e-12')
    return value == quoted


def _percent_matches(value, quoted, decimals):
    """Text percentages are quoted loosely; allow half a unit of last digit."""
    tolerance = max(0.5 * 10 ** -decimals, 0.1)   # percentage points
    return abs(value * 100.0 - float(quoted)) <= tolerance


def grade_claims(claims, records, re_tau_canonical):
    """Trace every claim to artifact records and classify the match."""
    graded = []
    for claim in claims:
        candidates = [r for r in records
                      if r['quantity'] == claim['quantity']
                      and r['model'] == claim['model']
                      and r['n'] == claim['n']
                      and r['window'] == claim['window']
                      and r['norm'] == 'rms_rel_unweighted']
        hits = [r for r in candidates if _rounds_to(r['value'], claim['quoted'])]
        canonical = [r for r in hits if r['re_tau'] == re_tau_canonical]
        vintages = sorted({r['re_tau'] for r in hits})
        if canonical:
            status = 'CANONICAL'
        elif hits:
            status = 'SNAPSHOT_ONLY'
        else:
            status = 'MISMATCH'
        reference = canonical or hits
        graded.append(dict(claim, status=status,
                           matching_vintages=vintages,
                           resolved=reference[0]['value'] if reference else None,
                           verifier=reference[0]['verifier'] if reference else None,
                           candidates=sorted({r['re_tau'] for r in candidates})))
    return graded


def grade_text(claims, records, re_tau_canonical):
    """Same traceability rule for prose percentages."""
    graded = []
    for claim in claims:
        graded_error = [r for r in records
                    if r['quantity'] == 'rms_relative'
                    and r['norm'] == 'rms_rel_unweighted'
                    and r['window'] in (LEGACY, LOG_LAYER)]
        canon_hit = [r for r in graded_error
                     if r['re_tau'] == re_tau_canonical
                     and _percent_matches(r['value'], claim['quoted'], claim['decimals'])]
        any_hit = [r for r in graded_error
                   if _percent_matches(r['value'], claim['quoted'], claim['decimals'])]
        vintages = sorted({r['re_tau'] for r in any_hit})
        if canon_hit:
            status = 'CANONICAL'
        elif any_hit:
            status = 'SNAPSHOT_ONLY'
        else:
            status = 'UNTRACEABLE'
        graded.append(dict(claim, status=status, matching_vintages=vintages,
                           verifier=(canon_hit or any_hit)[0]['verifier']
                           if (canon_hit or any_hit) else None))
    return graded


# --------------------------------------------------------------------------- #
# Gate
# --------------------------------------------------------------------------- #

BLOCKING = ('SNAPSHOT_ONLY', 'MISMATCH', 'UNTRACEABLE')


def audit(catalog_path=None, root=None):
    """Run the gate; ``verdict == 'PASS'`` only when every decimal is canonical."""
    root = ROOT if root is None else Path(root)
    records, present = load_records(root)
    canonical = canonical_re_tau()
    canonical_json = json.loads((root / 'docs' / 'case-fvm-channel-kmm180'
                                 / 'benchmark.json').read_text())
    recorded = 'nominal_re_tau' in canonical_json
    catalog, _ = load_catalog(catalog_path)
    graded = grade_claims(catalog_claims(catalog), records, canonical)
    text = grade_text(text_claims(catalog), records, canonical)

    blocking = ([{'kind': 'number', **g} for g in graded if g['status'] != 'CANONICAL']
                + [{'kind': 'text', **g} for g in text if g['status'] != 'CANONICAL'])
    vintages = sorted({r['re_tau'] for r in records if r['re_tau'] is not None})
    return dict(
        verdict='PASS' if not blocking else 'FAIL',
        canonical_re_tau=canonical,
        canonical_re_tau_recorded=recorded,
        record_vintages=vintages,
        artifacts=[{'path': rel, 'canonical': flag} for rel, flag in present],
        records=len(records),
        claims=graded,
        text=text,
        blocking=blocking,
    )


# --------------------------------------------------------------------------- #
# Repair: write the canonical decimal into the catalog
# --------------------------------------------------------------------------- #

def repair(catalog_path=None, root=None):
    """Rewrite each non-canonical decimal with the canonical artifact value.

    The value is copied from the artifact record (never retyped) and formatted to
    the number of decimals the entry already uses, so the diff is exactly the
    numbers that could not be reproduced by ``repro_cmd``.
    """
    root = ROOT if root is None else Path(root)
    records, _ = load_records(root)
    canonical = canonical_re_tau()
    catalog, _ = load_catalog(catalog_path)
    graded = grade_claims(catalog_claims(catalog), records, canonical)

    changes = []
    for entry in graded:
        if entry['status'] == 'CANONICAL':
            continue
        target = [r for r in records
                  if r['quantity'] == entry['quantity']
                  and r['model'] == entry['model'] and r['n'] == entry['n']
                  and r['window'] == entry['window']
                  and r['re_tau'] == canonical
                  and r['norm'] == 'rms_rel_unweighted']
        if not target:
            raise LookupError(
                f'{entry["field"]}: no canonical record to repair from '
                f'(quantity={entry["quantity"]})')
        value = target[0]['value']
        if entry['quantity'] == 'verdict':
            formatted = value
        elif isinstance(entry['quoted'], Decimal):
            exponent = entry['quoted'].as_tuple().exponent
            formatted = Decimal(repr(value)).quantize(Decimal(1).scaleb(exponent))
            if entry['quantity'] == 'cells':
                formatted = int(formatted)
        else:
            formatted = value
        changes.append(dict(field=entry['field'], old=str(entry['quoted']),
                            new=str(formatted), source=target[0]['verifier']))
        _set(catalog, entry['field'], formatted)
    return catalog, changes


def repair_benchmark_vintage(path=None):
    """Write the solved Re_tau into the canonical artifact (additive field)."""
    path = (CASE_DIR / 'benchmark.json') if path is None else Path(path)
    data = json.loads(path.read_text())
    if 'nominal_re_tau' in data:
        return data, None
    value = _driver_nominal_re_tau()
    out = {}
    for key, node in data.items():
        out[key] = node
        if key == 'reference':
            pass
    out['nominal_re_tau'] = value
    return out, dict(field='case-fvm-channel-kmm180/benchmark.json:nominal_re_tau',
                     new=str(value),
                     source='tensorfvm.benchmark_channel_kmm1987.run_case default')


def repair_prose(catalog, records=None, canonical=None):
    """Rewrite a prose percentage that only a superseded vintage reproduces.

    The replacement is the canonical record whose percentage is closest to the
    quoted token, formatted to the token's own precision; a token that no
    canonical record comes within 20 % of is left alone and stays reported (a
    prose number nobody can source is a finding, not something to paper over).
    """
    records = load_records()[0] if records is None else records
    canonical = canonical_re_tau() if canonical is None else canonical
    graded = grade_text(text_claims(catalog), records, canonical)
    candidates = [r for r in records
                  if r['quantity'] == 'rms_relative'
                  and r['norm'] == 'rms_rel_unweighted'
                  and r['window'] in (LEGACY, LOG_LAYER)
                  and r['re_tau'] == canonical]
    pending = {}
    for item in graded:
        if item['status'] == 'CANONICAL' or not candidates:
            continue
        best = min(candidates, key=lambda r: abs(r['value'] * 100 - float(item['quoted'])))
        delta = abs(best['value'] * 100 - float(item['quoted']))
        if delta > 0.2 * max(float(item['quoted']), 1e-9):
            continue
        pending.setdefault(item['field'], []).append(
            (item['token'], f"{best['value'] * 100:.{item['decimals']}f}",
             best['verifier'], float(item['quoted'])))

    changes = []
    for field, swaps in pending.items():
        node = _dig(catalog, field)
        if not isinstance(node, str):
            continue
        queue = list(swaps)
        out, last = [], 0
        for match in _PERCENT.finditer(node):
            if queue and match.group(1) == queue[0][0]:
                _, new, verifier, old = queue.pop(0)
                out.append(node[last:match.start(1)])
                out.append(new)
                last = match.end(1)
                changes.append(dict(field=f'{field} (prose)', old=str(old), new=new,
                                    source=verifier))
        out.append(node[last:])
        _set(catalog, field, ''.join(out))
    return catalog, changes


def _set(catalog, dotted, value):
    *parents, leaf = dotted.split('.')
    node = catalog
    for part in parents:
        node = node[part]
    node[leaf] = value


def detect_indent(text, default=2):
    """Indent width the file already uses, so a repair stays a minimal diff."""
    for line in text.splitlines():
        if line.startswith(' ') and line.strip():
            return len(line) - len(line.lstrip(' '))
    return default


def render(node):
    """Serialise ``node`` with the indent width supplied by :func:`detect_indent`."""
    indent = node.pop('__indent__', 2) if isinstance(node, dict) else 2
    return json.dumps(_floats(node), indent=indent, ensure_ascii=False) + '\n'


def _floats(node):
    if isinstance(node, Decimal):
        return float(node) if node.as_tuple().exponent < 0 else int(node)
    if isinstance(node, dict):
        return {key: _floats(value) for key, value in node.items()}
    if isinstance(node, list):
        return [_floats(value) for value in node]
    return node


