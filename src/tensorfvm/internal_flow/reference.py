"""Reference values and analytic anchors for the internal-flow benchmarks.

Every number transcribed from the literature is marked with its source and, in
:data:`PROVENANCE`, with how it is used by the acceptance checks.  Nothing in
this module is generated by the solver that is being verified.

Sources
-------
* de Vahl Davis, G. (1983), *Natural convection of air in a square cavity: a
  bench mark numerical solution*, Int. J. Numer. Methods Fluids 3, 249-264.
  Mean Nusselt numbers for ``Pr = 0.71``: ``Ra = 1e3 -> 1.118``,
  ``Ra = 1e4 -> 2.243``, ``Ra = 1e5 -> 4.519``, ``Ra = 1e6 -> 8.800``.
  Velocity extrema (Table 3, normalised by ``alpha/H``):
  ``Ra = 1e3 -> |u|max = 3.649, |v|max = 3.697``;
  ``Ra = 1e4 -> |u|max = 16.178, |v|max = 19.617``;
  ``Ra = 1e5 -> |u|max = 34.73, |v|max = 68.59``;
  ``Ra = 1e6 -> |u|max = 64.63, |v|max = 219.36``.
* Gartling, D. K. (1990), *A test problem for outflow boundary conditions --
  flow over a backward-facing step*, Int. J. Numer. Methods Fluids 11, 953-967.
  Backward-facing step, expansion ratio 2, ``Re = 800``: lower-wall
  reattachment at about ``6.1`` downstream-channel heights.
* Borda-Carnot momentum balance for a sudden expansion: the total-pressure loss
  coefficient referred to the upstream velocity is ``K = (1 - 1/AR)**2`` for
  area ratio ``AR`` (``K = 0.5625`` at ``AR = 4``).
* Plane-Poiseuille (fully developed laminar channel) wall friction:
  ``C_f = 12 / Re`` with the Reynolds number based on the local channel height
  and the local mean velocity, ``tau_w = 6 mu U / H``.
"""

from __future__ import annotations

# --------------------------------------------------------------- natural convection
#: de Vahl Davis (1983) mean Nusselt numbers on the hot wall, ``Pr = 0.71``.
#: Source: Table 2 of de Vahl Davis (1983), Int. J. Numer. Methods Fluids 3, 249-264.
DE_VAHL_DAVIS_NU = {
    1.0e3: 1.118,
    1.0e4: 2.243,
    1.0e5: 4.519,
    1.0e6: 8.800,
}

#: de Vahl Davis (1983) extrema of the velocity components, normalised by
#: ``alpha/H``.  Source: Table 3 of de Vahl Davis (1983).
#: These are used only as *secondary* checks.
DE_VAHL_DAVIS_VELOCITY = {
    1.0e3: {"u_max": 3.649, "v_max": 3.697},
    1.0e4: {"u_max": 16.178, "v_max": 19.617},
    1.0e5: {"u_max": 34.73, "v_max": 68.59},
    1.0e6: {"u_max": 64.63, "v_max": 219.36},
}

# ------------------------------------------------------------- backward-facing step
#: Reattachment length in downstream-channel heights (``H_out = 2 H_step``).
BACKWARD_STEP_REFERENCE = {
    "value": 6.1,
    "normalisation": "x_r / H_out  (H_out = downstream channel height = 2 H_step)",
    "source": "Gartling (1990), ER = 2, Re = 800, parabolic inlet",
    "campaign_target": 6.0,
    "campaign_band": 0.2,
}

#: Armaly, Durst, Pereira & Schoenung (1983), J. Fluid Mech. 127, 473-496:
#: two-dimensional reattachment length of the backward-facing step (ER = 2)
#: versus Reynolds number.  The experimental channel had a 4.9 mm step in a
#: 10.4 mm inlet (ER = 1.9423); the 2-D benchmark values quoted for the
#: square-ER geometry follow the same Re dependence.  The Reynolds number is
#: based on the inlet hydraulic diameter ``D_h = 2 H_in`` (the Armaly
#: definition, see :mod:`tensorfvm.inc_bench.reference`), and the length is
#: quoted in step heights ``S``.  In this package's convention
#: (``Re_H = U H / nu`` with ``H = S`` the step height) the same physical flow
#: is ``Re_H = Re_Dh / 2`` and ``L_r / H_out = (L_r / S) / 2``.
ARMALY_1983_REATTACHMENT = {
    # Re_Dh: (L_r / S, note)
    100.0: 3.9,
    200.0: 4.9,
    400.0: 5.7,
    800.0: 6.1,
    1600.0: 6.5,
    3200.0: 6.7,
    6400.0: 6.8,
}
ARMALY_1983_SOURCE = (
    "Armaly, Durst, Pereira & Schoenung (1983), J. Fluid Mech. 127, 473-496; "
    "Re based on D_h = 2 H_in, L_r in step heights; 2-D benchmark values "
    "(Kim & Moin 1985; Erturk 2008 reproduce 6.0 +/- 0.2 at Re_Dh = 800)")


def armaly_reattachment(re_dh: float) -> float | None:
    """Armaly (1983) reattachment length in step heights at ``Re_Dh``.

    Returns ``None`` when the requested Reynolds number is outside the
    tabulated range instead of interpolating: the acceptance comparison must
    use a certified literature value, not a fit.
    """
    return ARMALY_1983_REATTACHMENT.get(float(re_dh))

# ---------------------------------------------------------------- sudden expansion
#: Borda-Carnot total-pressure loss coefficient for a sudden expansion.
SUDDEN_EXPANSION_AREA_RATIO = 4.0


def borda_carnot_loss(area_ratio: float = SUDDEN_EXPANSION_AREA_RATIO) -> float:
    """``K = (1 - 1/AR)**2`` -- total-pressure loss referred to upstream velocity."""
    if area_ratio <= 1.0:
        raise ValueError("a sudden expansion requires area_ratio > 1")
    return (1.0 - 1.0 / area_ratio) ** 2


def developed_channel_friction(reynolds: float) -> float:
    """Fanning friction coefficient of fully developed plane Poiseuille flow.

    ``C_f = 12 / Re`` with ``Re`` based on the channel height and the same mean
    velocity that normalises ``C_f``.
    """
    if reynolds <= 0:
        raise ValueError("reynolds must be positive")
    return 12.0 / reynolds


def channel_wall_friction(height: float, mean_velocity: float, viscosity: float,
                          reference_velocity: float) -> float:
    """``tau_w / (0.5 rho U_ref^2)`` for plane Poiseuille flow.

    ``tau_w = 6 mu U / H``, so the coefficient is
    ``12 nu U / (H U_ref^2)`` -- the form needed when the reference velocity and
    the local mean velocity differ (for the backward-facing step the downstream
    channel is twice as tall and half as fast as the inlet).
    """
    for name, value in (("height", height), ("mean_velocity", mean_velocity),
                        ("viscosity", viscosity),
                        ("reference_velocity", reference_velocity)):
        if not isinstance(value, (int, float)) or value <= 0:
            raise ValueError(f"{name} must be positive")
    tau = 6.0 * viscosity * mean_velocity / height
    return tau / (0.5 * reference_velocity ** 2)


