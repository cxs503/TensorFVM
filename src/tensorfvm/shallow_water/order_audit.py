"""Why the dam-break benchmark converges at first order: an order-of-accuracy audit.

Motivation
----------
``docs/case-fvm-dambreak-stoker/case_pool_entry.json`` advertises
``solver.order = 2`` (MUSCL/minmod + HLL + SSP-RK, ``shallow_water/swe1d.py``),
while every committed convergence measurement of the anchored case reports an
*observed* order of about **1.0** (depth L1: 1.011 / 0.988 in ``REPORT.md``;
``x_f(t)`` series 0.68-0.73 in ``case-fvm-dambreak-stoker-hires/``).  The merged
report explains the gap with "a TVD scheme at a discontinuity is first order".
That sentence is a statement about the *format*, it does not say which
singularity owns the error, and no committed experiment can falsify it.

This module makes the claim testable by separating the two things an observed
order can be limited by: the **operator** and the **data** (or the solution).

``smooth_bump_study``
    A Gaussian bump in a still basin evolved for ``t = 1`` and compared with
    *itself* on a refinement ladder (3-grid Richardson through cell-average
    restriction).  The solution stays smooth, so the observed order is the order
    of the operator; no reference solution and no hand-typed number is used.

``fan_interior_study``
    The anchored Ritter/Stoker rarefaction graded **only inside the fan
    interior**: a margin of ``FAN_INTERIOR_FRACTION`` of the analytically known
    fan width is trimmed at each end (``ritter_fan_window`` /
    ``stoker_fan_window``), so the dry front, the bore and the two fan kinks are
    outside the graded window.  Two initialisations are compared:

    ``step``    the physical dam break -- a *discontinuous* initial depth;
    ``smooth``  a restart from the closed form at ``t* = SMOOTH_INIT_T_STAR``.
                For the dry bed these data are continuous (the Ritter profile is
                a smooth fan between two constants, with one slope kink at the
                tail), so the dry-bed pair isolates *data* regularity.  For the
                wet bed the closed form already contains the bore, i.e. the wet
                bed cannot be regularised -- see the honest-scope note below.

Measured (generated by :func:`audit`; see
``docs/case-fvm-dambreak-order-audit/REPORT.md``):

* smooth bump: asymptotic order **2.04** (fit 1.99) -> the operator is genuinely
  second order, so ``solver.order = 2`` is true **in its own scope**;
* Ritter dry bed, ``step`` init: **1.00**; the *same* solution restarted from
  continuous data: **1.98**.  The loss of order is therefore owned by the
  discontinuous initial data, not by the operator.  The interior error is a
  genuine ``O(dx)`` self-similar limit: ``err/dx`` vs ``xi`` collapses to
  **1.0 %** between the two finest grids;
* Stoker wet bed, ``step`` init: **1.04**, ``err/dx`` collapse **0.6 %**, i.e.
  also a clean ``O(dx)`` limit.  The restart sequence is **non-monotone**
  (orders -0.05, 0.56, 2.21, 3.20), so no order is quoted for it
  (``gradable = False``): the bore is an intrinsic travelling discontinuity and
  first order there belongs to the *solution*, not to the startup.

Consequence for the case pool
-----------------------------
The pool grades ``x_f(t)``, the still-water step and monotonicity at a fixed
grid with a 5 % tolerance; convergence order is **not** a gate, so none of this
changes the acceptance verdict.  What the entry must not imply is that the
graded case converges at the design order.  :func:`audit_entry_claim` binds the
advertised order to the smooth-regime measurement and emits the scope note the
entry needs; an over-advertised order (e.g. 3 for this scheme) is rejected.

Honest scope
------------
* The restart experiment is a *regularity* experiment, not a different physical
  problem: it uses the same equations, the same grid family and the same
  end time, and only replaces the singular initial data with the closed form.
  It cannot be run for the wet bed, which is why the wet bed is graded as
  "intrinsic, order 1" and its restart is explicitly withheld.
* A first-order global L1 error for a conservation law with a discontinuity is
  the classical result (LeVeque 2002, ch. 8); this module does not rediscover
  it, it identifies *which* singularity in *this* case is responsible and
  certifies that the operator itself is not the cause.
* Convergence order says nothing about the 5 % acceptance margins at the graded
  grid; those are graded by ``shallow_water/dam_break.py`` and unchanged.

References
----------
Ritter (1892); Stoker (1957) ch. 10 -- closed forms, via
:mod:`tensorfvm.shallow_water.exact`.
Roache (1998), *Verification and Validation in Computational Science and
Engineering*, ch. 5 -- observed order from three grids.
LeVeque (2002), *Finite Volume Methods for Hyperbolic Problems*, ch. 8.
"""

