def load_case_pool_entry(path: Optional[pathlib.Path] = None) -> Dict[str, Any]:
    """Load the committed ``case_pool_entry.json`` of the anchored case."""
    p = pathlib.Path(path) if path is not None else ENTRY_PATH
    return json.loads(p.read_text(encoding="utf-8"))


def audit_entry_claim(record: Dict[str, Any],
                      entry: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Grade the pool entry's advertised ``solver.order`` against the audit.

    ``SUPPORTED`` when the measured smooth-regime order matches the advertised
    one; ``OVERSTATED`` when the entry claims more order than the operator
    delivers (nothing in the discretisation could then justify the claim);
    ``UNDERSTATED`` when far below; ``WITHHELD`` when unmeasurable.  The
    dam-break orders are reported alongside so the entry cannot be read as
    certifying the graded case at the design order.
    """
    ent = entry if entry is not None else load_case_pool_entry()
    advertised = ent.get("solver", {}).get("order")
    if advertised is None:
        return {"status": "WITHHELD", "reason": "entry advertises no solver.order",
                "advertised_order": None}
    advertised = int(advertised)
    smooth = record["measured"]["smooth_regime"]
    measured = float(smooth["order_asymptotic"])
    dam_break = {k: (None if math.isnan(float(v["order_asymptotic"]))
                     else float(v["order_asymptotic"]))
                 for k, v in record["measured"]["dam_break"].items()}
    if math.isnan(measured) or not smooth.get("gradable", True):
        status = "WITHHELD"
        reason = "smooth-regime order is not measurable from this ladder"
    elif abs(measured - advertised) <= ORDER_TOLERANCE:
        status = "SUPPORTED"
        reason = (f"smooth-regime order {measured:.2f} matches the advertised "
                  f"{advertised} within {ORDER_TOLERANCE}")
    elif advertised > measured:
        status = "OVERSTATED"
        reason = (f"entry advertises order {advertised} but the operator measures "
                  f"{measured:.2f} in the smooth regime")
    else:
        status = "UNDERSTATED"
        reason = (f"entry advertises order {advertised}, the operator measures "
                  f"{measured:.2f} in the smooth regime")
    db_text = ", ".join(f"{k}: {v:.2f}" for k, v in sorted(dam_break.items())
                        if v is not None)
    withh = [k for k, v in dam_break.items() if v is None]
    return {
        "status": status,
        "reason": reason,
        "advertised_order": advertised,
        "measured_smooth_order": measured,
        "measured_order_tolerance": ORDER_TOLERANCE,
        "measured_dam_break_order": dam_break,
        "dam_break_order_withheld": withh,
        "required_scope_note": (
            "the advertised order describes the *smooth-regime* operator "
            f"(measured {measured:.2f}); the anchored dam-break itself converges "
            f"at {db_text}, because the dry bed starts from a discontinuous dam "
            "and the wet bed carries a bore, so no order should be quoted for "
            "the graded case" + (f" ({', '.join(withh)} not gradable)" if withh else "")),
        "graded_quantities_unaffected": (
            "the pool grades x_f(t), the still-water step and monotonicity at a "
            "fixed grid with 5 %; convergence order is not a gate, so this "
            "finding does not change the acceptance verdict"),
    }


