#: fraction of the fan width trimmed at each fan end before grading.  Both ends
#: are places where the closed form is not differentiable (the tail kink, and
#: the dry front / the rarefaction-bore match); grading a cell that straddles
#: them measures the resolution of a kink, not the order of the interior.
FAN_INTERIOR_FRACTION = 0.15

#: exact-solution restart time of the regularity experiment (``t* = 0`` is the
#: dam; by ``0.5`` the dry front has travelled ~2 units and the fan holds
#: hundreds of cells on the graded ladders).
SMOOTH_INIT_T_STAR = 0.5

#: accepted deviation between the advertised ``solver.order`` and the measured
#: smooth-regime order.  A second-order scheme measured at 1.9 is still second
#: order (the estimate is the mean of the two finest pair orders); 0.3 leaves
#: room for residual low-order contamination of the Gaussian bump but cannot
#: accommodate a first-order measurement.
ORDER_TOLERANCE = 0.3

#: an ``err/dx`` profile that is grid independent to this level is evidence that
#: the interior error is an ``O(dx)`` self-similar limit rather than an
#: under-resolved estimator artefact.  5 % is 2-5x the measured value on the
#: finest pair of both anchored cases (1.0 % dry, 0.6 % wet).
ODX_COLLAPSE_TOLERANCE = 0.05

#: order gates: a case whose interior error decays at ``O(dx)`` must measure at
#: or below ``FIRST_ORDER_CEILING``; a case that recovers the design order must
#: measure at or above ``SECOND_ORDER_FLOOR`` (1.7 admits ~15 % low bias from
#: the remaining low-order contamination, as measured: 1.98).
FIRST_ORDER_CEILING = 1.3
SECOND_ORDER_FLOOR = 1.7

#: smooth self-convergence problem: a Gaussian bump in a still basin, evolved
#: for a time short enough that the two outgoing wave packets stay far from the
#: transmissive ends (the fastest wave travels ``(c0 + A) t ~ 3.5`` of a 20-unit
#: half-domain).
SMOOTH_BUMP: Dict[str, float] = {
    "depth": 1.0,
    "amplitude": 0.1,
    "width": 2.0,
    "x_min": -20.0,
    "x_max": 20.0,
    "t_end": 1.0,
    "gravity": 9.81,
}

