# --------------------------------------------------------------------------- #
# analytic windows (derived from the closed forms, never tabulated)
# --------------------------------------------------------------------------- #
def _check_fraction(fraction: float) -> None:
    if not 0.0 <= fraction < 0.5:
        raise ValueError("fraction must be in [0, 0.5)")


def ritter_fan_window(h0: float, gravity: float = 9.81,
                      fraction: float = FAN_INTERIOR_FRACTION) -> Dict[str, float]:
    """Similarity window of the Ritter fan interior, ``xi = (x - x_dam)/t``.

    The dry-bed fan spans ``-c0 <= xi <= 2 c0``; ``lo``/``hi`` are that interval
    with ``fraction`` of its width trimmed at each end.
    """
    _check_fraction(fraction)
    c0 = math.sqrt(gravity * h0)
    lo_full, hi_full = -c0, 2.0 * c0
    width = hi_full - lo_full
    return {
        "lo": lo_full + fraction * width,
        "hi": hi_full - fraction * width,
        "lo_full": lo_full,
        "hi_full": hi_full,
        "width_full": width,
    }


def stoker_fan_window(h0: float, h1: float, gravity: float = 9.81,
                      fraction: float = FAN_INTERIOR_FRACTION) -> Dict[str, float]:
    """Similarity window of the Stoker left rarefaction, from the closed form.

    ``stoker_region_bounds`` provides ``head = -c0`` and ``tail = u2 - c2``; the
    fan is ``head < xi < tail``.  Trimming ``fraction`` of that width at each end
    also keeps the constant post-bore state and the bore itself out of the
    graded window.
    """
    _check_fraction(fraction)
    bounds = stoker_region_bounds(h0, h1, gravity)
    lo_full = float(bounds["head"])
    hi_full = float(bounds["tail"])
    if not hi_full > lo_full:
        raise ValueError("Stoker rarefaction has no interior at this depth ratio")
    width = hi_full - lo_full
    return {
        "lo": lo_full + fraction * width,
        "hi": hi_full - fraction * width,
        "lo_full": lo_full,
        "hi_full": hi_full,
        "width_full": width,
        "shock": float(bounds["shock"]),
        "u2": float(bounds["u2"]),
        "h2": float(bounds["h2"]),
    }


def case_fan_window(case: DamBreakCase,
                    fraction: float = FAN_INTERIOR_FRACTION) -> Dict[str, float]:
    """Analytic fan-interior window for a dam-break case (dry or wet bed)."""
    if case.kind == "dry":
        return ritter_fan_window(case.h0, case.gravity, fraction)
    return stoker_fan_window(case.h0, case.h1, case.gravity, fraction)


def fan_mask(xi, lo: float, hi: float) -> np.ndarray:
    """Cells whose similarity coordinate lies strictly inside ``(lo, hi)``."""
    xi = np.asarray(xi, dtype=float)
    return (xi > lo) & (xi < hi)


# --------------------------------------------------------------------------- #
# small numeric helpers
# --------------------------------------------------------------------------- #
def _restrict(fine: np.ndarray, n_coarse: int) -> np.ndarray:
    """Cell-average restriction of a ``2 n_coarse`` solution onto ``n_coarse``.

    Both grids are uniform on the same domain with the same ``x_min``, so coarse
    cell ``k`` is exactly the union of fine cells ``2k`` and ``2k+1``.
    """
    fine = np.asarray(fine, dtype=float)
    if fine.size != 2 * n_coarse:
        raise ValueError(
            f"restriction needs a 2x fine grid: {fine.size} vs 2*{n_coarse}")
    return fine.reshape(n_coarse, 2).mean(axis=1)


def _l1(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.mean(np.abs(np.asarray(a) - np.asarray(b))))


def _fit_order(dx: Sequence[float], err: Sequence[float]) -> float:
    """Least-squares slope of ``log(err)`` against ``log(dx)``."""
    dx = np.asarray(dx, dtype=float)
    err = np.asarray(err, dtype=float)
    ok = err > 0.0
    if int(np.count_nonzero(ok)) < 2:
        return float("nan")
    return float(np.polyfit(np.log(dx[ok]), np.log(err[ok]), 1)[0])


def _is_monotone_decreasing(values: Sequence[float]) -> bool:
    """True when every refinement strictly reduces the error.

    An order estimate from a non-monotone sequence is meaningless; this is the
    flag that decides whether a study is *gradable* at all.
    """
    return all(b < a for a, b in zip(values[:-1], values[1:]))


# --------------------------------------------------------------------------- #
# smooth self-convergence problem
# --------------------------------------------------------------------------- #
def smooth_bump_state(x, depth: float = SMOOTH_BUMP["depth"],
                      amplitude: float = SMOOTH_BUMP["amplitude"],
                      width: float = SMOOTH_BUMP["width"]) -> np.ndarray:
    """Still-water Gaussian bump centred in the basin: a ``C^inf`` initial depth.

    No reference solution is needed -- the smooth study compares the solver with
    itself on refined grids -- so the bump only has to keep the solution smooth
    and away from the transmissive ends over ``t_end``.
    """
    x = np.asarray(x, dtype=float)
    return depth + amplitude * np.exp(-(x / width) ** 2)


def smooth_bump_study(resolutions: Iterable[int] = (200, 400, 800, 1600, 3200),
                      order: int = 2, cfl: float = 0.4,
                      config: Optional[Dict[str, float]] = None) -> Dict[str, Any]:
    """Self-convergence of the solver on a **smooth** problem.

    Graded quantity: the L1 difference between the solution on ``n`` and the
    cell-average restriction of the solution on ``2n``.  Three grids give a
    Richardson order; no reference solution is involved, so the result measures
    the discretisation alone.
    """
    cfg = dict(SMOOTH_BUMP)
    if config:
        cfg.update(config)
    ns = [int(n) for n in resolutions]
    runs: Dict[int, np.ndarray] = {}
    rows: List[Dict[str, Any]] = []
    for n in ns:
        solver = ShallowWater1D(n, cfg["x_min"], cfg["x_max"],
                                gravity=cfg["gravity"], cfl=cfl, order=order)
        solver.set_state(smooth_bump_state(solver.x, cfg["depth"],
                                           cfg["amplitude"], cfg["width"]))
        volume0 = solver.total_volume()
        steps = solver.advance(cfg["t_end"])
        runs[n] = solver.h.copy()
        rows.append({
            "n": n,
            "dx": solver.dx,
            "steps": int(steps),
            "time": float(solver.time),
            "volume_drift": float(solver.total_volume() / volume0 - 1.0),
            "clipped_cells": int(solver.clipped_cells),
            "dry_flips": int(solver.dry_flips),
        })
    pairs: List[Dict[str, Any]] = []
    for n, n2 in zip(ns[:-1], ns[1:]):
        if n2 != 2 * n:
            continue
        pairs.append({"n": n, "n_fine": n2,
                      "l1": _l1(runs[n], _restrict(runs[n2], n))})
    order_pairs = []
    for a, b in zip(pairs[:-1], pairs[1:]):
        order_pairs.append({
            "n_coarsest": a["n"],
            "order": (math.log2(a["l1"] / b["l1"]) if b["l1"] > 0.0
                      else float("nan")),
        })
    asymptotic = [p["order"] for p in order_pairs[-2:]
                  if not math.isnan(p["order"])]
    pairs_l1 = [p["l1"] for p in pairs]
    return {
        "problem": {"kind": "smooth-gaussian-bump", **cfg, "order": order, "cfl": cfl},
        "rows": rows,
        "pairs": pairs,
        "observed_order_pairs": order_pairs,
        "observed_order_fit": _fit_order(
            [(cfg["x_max"] - cfg["x_min"]) / p["n"] for p in pairs], pairs_l1),
        "observed_order_asymptotic": (float(np.mean(asymptotic)) if asymptotic
                                      else float("nan")),
        "finest_l1": (float(pairs_l1[-1]) if pairs_l1 else float("nan")),
        "error_monotone": _is_monotone_decreasing(pairs_l1),
        "gradable": _is_monotone_decreasing(pairs_l1),
    }


# --------------------------------------------------------------------------- #
# dam-break fan interior
# --------------------------------------------------------------------------- #
def _fan_run(case: DamBreakCase, n: int, init: str, cfl: float, order: int,
             t_star_end: float, t_star_init: float) -> Dict[str, Any]:
    """One dam-break run, graded inside the analytic fan window only."""
    solver = ShallowWater1D(n, case.x_min, case.x_max, gravity=case.gravity,
                            cfl=cfl, order=order)
    t_begin = t_star_to_time(t_star_init, case.h0, case.gravity)
    t_end = t_star_to_time(t_star_end, case.h0, case.gravity)
    if init == "step":
        if t_star_init != 0.0:
            raise ValueError("the discontinuous (step) initialisation is at t* = 0")
        solver.set_state(np.where(solver.x < case.x_dam, case.h0, case.h1))
    elif init == "smooth":
        h_ex, u_ex = case.exact(solver.x, t_begin)
        solver.set_state(h_ex, u_ex)
        solver.time = t_begin
    else:  # pragma: no cover - guarded by the public entry points
        raise ValueError(f"unknown initialisation {init!r}")
    steps = solver.advance(t_end)
    h_ex, _ = case.exact(solver.x, solver.time)
    window = case_fan_window(case)
    xi = (solver.x - case.x_dam) / solver.time
    mask = fan_mask(xi, window["lo"], window["hi"])
    err = solver.h - h_ex
    return {
        "n": int(n),
        "dx": solver.dx,
        "steps": int(steps),
        "time": float(solver.time),
        "t_star": float(solver.time / math.sqrt(case.h0 / case.gravity)),
        "window_cells": int(np.count_nonzero(mask)),
        "window_fraction": float(np.count_nonzero(mask) / solver.n),
        "interior_l1": float(np.mean(np.abs(err[mask]))),
        "interior_linf": float(np.max(np.abs(err[mask]))),
        "clipped_cells": int(solver.clipped_cells),
        "dry_flips": int(solver.dry_flips),
        "_xi": xi,
        "_err": err,
    }


def fan_interior_study(case: DamBreakCase, init: str = "step",
                       resolutions: Iterable[int] = (100, 200, 400, 800, 1600),
                       order: int = 2, cfl: float = 0.4,
                       t_star_end: float = 2.0,
                       t_star_init: float = SMOOTH_INIT_T_STAR,
                       fraction: float = FAN_INTERIOR_FRACTION,
                       collapse_samples: int = 200) -> Dict[str, Any]:
    """Observed order of the dam-break solution **inside the fan interior**.

    ``init = 'step'`` is the physical dam break (discontinuous data);
    ``init = 'smooth'`` restarts from the closed form at ``t* = t_star_init``.
    For the dry bed that removes the discontinuity from the data; for the wet
    bed it does not, because the closed form already carries the bore.

    Also measures the ``err/dx`` **collapse**: where the interior error is a
    genuine ``O(dx)`` self-similar limit, ``err/dx`` against ``xi`` is grid
    independent.  The collapse metric is the max difference between consecutive
    grids' normalised profiles, sampled on a common ``xi`` grid inside the
    window; the finest pair is the reported evidence, the rest is diagnostic.
    """
    if init not in ("step", "smooth"):
        raise ValueError("init must be 'step' or 'smooth'")
    ns = [int(n) for n in resolutions]
    raw = [_fan_run(case, n, init, cfl, order, t_star_end,
                    t_star_init if init == "smooth" else 0.0) for n in ns]
    rows = [{k: v for k, v in r.items() if not k.startswith("_")} for r in raw]
    l1 = [r["interior_l1"] for r in rows]
    linf = [r["interior_linf"] for r in rows]
    orders_l1 = [{"n_coarsest": a, "order": (math.log2(b / c) if c > 0 else float("nan"))}
                 for a, b, c in zip(ns[:-2], l1[:-2], l1[1:])]
    orders_linf = [{"n_coarsest": a, "order": (math.log2(b / c) if c > 0 else float("nan"))}
                   for a, b, c in zip(ns[:-2], linf[:-2], linf[1:])]

    window = case_fan_window(case, fraction)
    xi_common = np.linspace(window["lo"], window["hi"], int(collapse_samples))
    normalised = []
    for run in raw:
        perm = np.argsort(run["_xi"])
        normalised.append(np.interp(xi_common, run["_xi"][perm],
                                    (run["_err"] / run["dx"])[perm]))
    collapse = []
    for i, (a, b) in enumerate(zip(normalised[:-1], normalised[1:])):
        scale = float(np.max(np.abs(b)))
        collapse.append({
            "n": ns[i],
            "n_fine": ns[i + 1],
            "max_abs_difference": float(np.max(np.abs(a - b))),
            "relative_to_finer_max": (float(np.max(np.abs(a - b)) / scale
                                            if scale > 0.0 else float("nan"))),
        })
    live = [c["relative_to_finer_max"] for c in collapse
            if not math.isnan(c["relative_to_finer_max"])]
    monotone = _is_monotone_decreasing(l1)
    asymptotic = [o["order"] for o in orders_l1[-2:] if not math.isnan(o["order"])]
    return {
        "case": case.key,
        "kind": case.kind,
        "reference": case.reference,
        "init": init,
        "t_star_end": float(t_star_end),
        "t_star_init": (float(t_star_init) if init == "smooth" else 0.0),
        "order": int(order),
        "cfl": cfl,
        "fan_window": window,
        "fraction": float(fraction),
        "rows": rows,
        "observed_order_l1": orders_l1,
        "observed_order_linf": orders_linf,
        "order_fit_l1": _fit_order([r["dx"] for r in rows], l1),
        "order_fit_linf": _fit_order([r["dx"] for r in rows], linf),
        "asymptotic_order_l1": (float(np.mean(asymptotic)) if asymptotic
                                else float("nan")),
        "error_monotone": monotone,
        #: an order is only quoted when refinement actually reduces the error
        "gradable": bool(monotone and len(asymptotic) > 0),
        "collapse": collapse,
        "collapse_worst_relative": (float(max(live)) if live else float("nan")),
        "collapse_finest_relative": (collapse[-1]["relative_to_finer_max"]
                                     if collapse else float("nan")),
        "xi_common": xi_common.tolist(),
    }


# --------------------------------------------------------------------------- #
# audit assembly
# --------------------------------------------------------------------------- #
def audit(resolutions_fan: Iterable[int] = (100, 200, 400, 800, 1600, 3200),
          resolutions_smooth: Iterable[int] = (200, 400, 800, 1600, 3200),
          order: int = 2, cfl: float = 0.4,
          t_star_end: float = 2.0) -> Dict[str, Any]:
    """Full order audit: smooth-regime certification + dam-break mechanism."""
    smooth = smooth_bump_study(resolutions_smooth, order=order, cfl=cfl)
    studies = {
        "ritter-dry/step": fan_interior_study(RITTER_DRY, "step", resolutions_fan,
                                              order=order, cfl=cfl,
                                              t_star_end=t_star_end),
        "ritter-dry/smooth": fan_interior_study(RITTER_DRY, "smooth", resolutions_fan,
                                                order=order, cfl=cfl,
                                                t_star_end=t_star_end),
        "stoker-wet/step": fan_interior_study(STOKER_WET, "step", resolutions_fan,
                                              order=order, cfl=cfl,
                                              t_star_end=t_star_end),
        "stoker-wet/smooth": fan_interior_study(STOKER_WET, "smooth", resolutions_fan,
                                                order=order, cfl=cfl,
                                                t_star_end=t_star_end),
    }
    measured = {
        "smooth_regime": {
            "order_asymptotic": smooth["observed_order_asymptotic"],
            "order_fit": smooth["observed_order_fit"],
            "gradable": smooth["gradable"],
        },
        "dam_break": {
            key: {"order_asymptotic": st["asymptotic_order_l1"],
                  "order_fit": st["order_fit_l1"],
                  "gradable": st["gradable"],
                  "error_monotone": st["error_monotone"],
                  "collapse_finest_relative": st["collapse_finest_relative"]}
            for key, st in studies.items()
        },
    }
    return {
        "discretisation": {"order": int(order), "cfl": cfl,
                           "module": "tensorfvm.shallow_water.swe1d"},
        "t_star_end": float(t_star_end),
        "fan_fraction": float(FAN_INTERIOR_FRACTION),
        "smooth_init_t_star": float(SMOOTH_INIT_T_STAR),
        "tolerances": {
            "order_tolerance": ORDER_TOLERANCE,
            "odx_collapse_tolerance": ODX_COLLAPSE_TOLERANCE,
            "first_order_ceiling": FIRST_ORDER_CEILING,
            "second_order_floor": SECOND_ORDER_FLOOR,
        },
        "smooth": smooth,
        "fan": studies,
        "measured": measured,
        "verdict": _verdict(measured, order),
    }


def _verdict(measured: Dict[str, Any], advertised_order: int) -> Dict[str, Any]:
    """Grade the claims this audit can decide mechanically.

    Each entry carries ``kind``: ``gate`` (a measurement that can fail) or
    ``diagnostic`` (reported, never gates).
    """
    checks: Dict[str, Dict[str, Any]] = {}

    def add(key: str, value: float, ok: bool, reason: str,
            kind: str = "gate") -> None:
        checks[key] = {"value": (None if isinstance(value, float) and math.isnan(value)
                                 else float(value)),
                       "pass": bool(ok) if kind == "gate" else None,
                       "kind": kind, "reason": reason}

    smooth = measured["smooth_regime"]
    db = measured["dam_break"]
    add("smooth_regime_order", smooth["order_asymptotic"],
        bool(smooth["gradable"])
        and abs(smooth["order_asymptotic"] - advertised_order) <= ORDER_TOLERANCE,
        f"Gaussian-bump self-convergence must reproduce the advertised order "
        f"{advertised_order} within {ORDER_TOLERANCE}")
    add("dry_bed_first_order_from_step", db["ritter-dry/step"]["order_asymptotic"],
        db["ritter-dry/step"]["order_asymptotic"] <= FIRST_ORDER_CEILING,
        "the anchored dry-bed case started from the dam discontinuity must be "
        "first order (that is the observed behaviour being explained)")
    add("dry_bed_error_is_odx", db["ritter-dry/step"]["collapse_finest_relative"],
        db["ritter-dry/step"]["collapse_finest_relative"] <= ODX_COLLAPSE_TOLERANCE,
        f"the dry-bed interior error must be an O(dx) self-similar limit "
        f"(err/dx collapse <= {ODX_COLLAPSE_TOLERANCE} on the finest pair)")
    add("dry_bed_operator_recovers_order", db["ritter-dry/smooth"]["order_asymptotic"],
        db["ritter-dry/smooth"]["order_asymptotic"] >= SECOND_ORDER_FLOOR,
        "the same dry-bed solution restarted from continuous data must recover "
        "~2: proof that the loss of order belongs to the data, not the operator")
    add("wet_bed_first_order_intrinsic", db["stoker-wet/step"]["order_asymptotic"],
        db["stoker-wet/step"]["order_asymptotic"] <= FIRST_ORDER_CEILING,
        "the wet bed owns a travelling bore, so it must stay first order even "
        "though the graded window excludes the bore")
    add("wet_bed_error_is_odx", db["stoker-wet/step"]["collapse_finest_relative"],
        db["stoker-wet/step"]["collapse_finest_relative"] <= ODX_COLLAPSE_TOLERANCE,
        "the wet-bed interior error must also be an O(dx) self-similar limit")
    # diagnostic: the wet-bed restart is not a regularisation, and its measured
    # sequence is non-monotone -- it must be reported, never quoted as an order
    wet_restart = db["stoker-wet/smooth"]
    add("wet_bed_restart_not_gradable", wet_restart["order_asymptotic"],
        not wet_restart["gradable"],
        "the wet-bed restart sequence must be reported as non-gradable "
        "(the closed form already contains the bore; no order is quoted)",
        kind="diagnostic")
    gates = [c for c in checks.values() if c["kind"] == "gate"]
    return {
        "checks": checks,
        "gates": len(gates),
        "all_gates_pass": all(c["pass"] for c in gates),
        "order_claim_supported": bool(checks["smooth_regime_order"]["pass"]),
    }


