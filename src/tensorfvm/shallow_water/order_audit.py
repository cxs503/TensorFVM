def _jsonable(obj: Any) -> Any:
    if isinstance(obj, dict):
        return {str(k): _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, (np.bool_, bool)):
        return bool(obj)
    if isinstance(obj, (np.floating, float)):
        value = float(obj)
        return None if math.isnan(value) else value
    if isinstance(obj, (np.integer, int)):
        return int(obj)
    return obj


def write_artifacts(record: Dict[str, Any],
                    outdir: Optional[pathlib.Path] = None,
                    entry_audit: Optional[Dict[str, Any]] = None) -> Dict[str, str]:
    """Write ``summary.json`` (+ optional ``entry_claim.json``); returns paths."""
    out = pathlib.Path(outdir) if outdir is not None else ARTIFACT_DIR
    out.mkdir(parents=True, exist_ok=True)
    written: Dict[str, str] = {}
    summary = out / "summary.json"
    summary.write_text(json.dumps(_jsonable(record), indent=2, sort_keys=True) + "\n",
                       encoding="utf-8")
    written["summary"] = str(summary)
    if entry_audit is not None:
        claim = out / "entry_claim.json"
        claim.write_text(json.dumps(_jsonable(entry_audit), indent=2, sort_keys=True)
                         + "\n", encoding="utf-8")
        written["entry_claim"] = str(claim)
    return written