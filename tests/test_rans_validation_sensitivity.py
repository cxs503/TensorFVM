"""Constant-sensitivity sweep and matrix-grading checks."""
import json
from pathlib import Path

import pytest

from tensorfvm.rans_validation.matrix import (CRITERIA, PRIMARY_FRACTION, grade, run_matrix,
                                              summarise)
from tensorfvm.rans_validation.sensitivity import constant_sweep

ARTIFACTS = Path(__file__).resolve().parents[1] / 'docs' / 'rans-turbulence-validation-matrix'


def test_sweep_is_anchored_at_the_unperturbed_constant():
    sweep = constant_sweep('sst', re_tau=590., n=64, changes=(-.1, 0., .1))
    zero = [row for row in sweep['rows'] if row['change'] == 0.]
    assert len(zero) == 1
    assert zero[0]['Cf'] == pytest.approx(sweep['base_Cf'], rel=1e-12)
    assert zero[0]['Cf_relative_change'] == pytest.approx(0., abs=1e-12)
    assert sweep['all_converged']


def test_sst_friction_response_is_stronger_than_the_budget():
    """beta* is the C_mu-equivalent of the k-omega family; measure its leverage."""
    sweep = constant_sweep('sst', re_tau=590., n=64, changes=(-.1, 0., .1))
    assert sweep['constant'] == 'beta_star'
    assert sweep['sensitivity_dCfdC_over_Cf'] < -1.
    assert sweep['max_abs_change_within_ten_percent'] > CRITERIA['constant_sensitivity']


def test_wall_function_kepsilon_is_insensitive_to_c_mu():
    sweep = constant_sweep('kepsilon', re_tau=590., n=32, changes=(-.1, 0., .1), first_cell_y_plus=30.)
    assert sweep['constant'] == 'c_mu'
    assert sweep['max_abs_change_within_ten_percent'] < .02
    assert sweep['max_abs_change_within_ten_percent'] < CRITERIA['constant_sensitivity']


def test_sweep_rejects_an_unknown_constant():
    with pytest.raises(ValueError):
        constant_sweep('sst', re_tau=590., n=32, constant='c_mu')


def test_quick_matrix_grades_every_case_explicitly():
    report = run_matrix(re_tau_values=(543.496, 590.), models=('sst', 'kepsilon'),
                        levels={'low_re': (64, 128), 'wall_function': (16, 32)},
                        cells={'low_re': 128, 'wall_function': 32}, sensitivity=False)
    assert len(report['cases']) == 4
    verdicts = [row for row in report['verdicts'] if row['criterion'] == 'log_region_deviation']
    assert len(verdicts) == 4
    for verdict in verdicts:
        primary = verdict['primary']
        assert primary['reference'] in ('dns', 'log_law')
        assert primary['passed'] == (primary['rms_relative'] < CRITERIA['log_region_deviation'])
        for alternative in verdict['alternatives'].values():
            assert alternative['passed'] == (alternative['rms_relative'] < CRITERIA['log_region_deviation'])
    for case in report['cases']:
        assert case['converged']
        assert case['grid_finest_Cf_change'] < .05
    assert 'sst' in summarise(report)


def test_grading_flags_a_deliberately_failing_case():
    report = dict(cases=[dict(model='toy', re_tau=590., deviations={
        'log_law': {('%.2f' % PRIMARY_FRACTION): dict(rms_relative=.2, max_relative=.3)},
        'reichardt': {('%.2f' % PRIMARY_FRACTION): dict(rms_relative=.25, max_relative=.3)}},
        local_kappa=None, implied_kappa=.4, Cf_deviation_vs_dns=None)],
        sensitivity=[dict(model='toy', constant='c', max_abs_change_within_ten_percent=.5)])
    verdicts = grade(report)
    assert verdicts[0]['primary']['reference'] == 'log_law'
    assert not verdicts[0]['primary']['passed']
    assert not verdicts[1]['passed']


@pytest.mark.skipif(not (ARTIFACTS / 'matrix.json').is_file(), reason='matrix artifact not generated')
def test_shipped_matrix_artifact_is_self_consistent():
    report = json.loads((ARTIFACTS / 'matrix.json').read_text(encoding='utf-8'))
    assert report['criteria'] == CRITERIA
    assert report['cases'] and report['grid'] and report['sensitivity']
    assert len(report['verdicts']) == len(report['cases']) + len(report['sensitivity'])
    for case in report['cases']:
        for name, per_fraction in case['deviations'].items():
            if name == 'dns':
                continue
            for row in per_fraction.values():
                assert row is None or row['rms_relative'] >= 0
        assert len(case['profiles']['y_plus']) == len(case['profiles']['u_plus']) == case['cells']
    for verdict in report['verdicts']:
        if verdict['criterion'] == 'log_region_deviation':
            assert verdict['local_kappa'] is None or verdict['local_kappa']['kappa_local'] > 0
    text = (ARTIFACTS / 'table.md').read_text(encoding='utf-8') if (ARTIFACTS / 'table.md').is_file() else ''
    assert 'Generated by' in text