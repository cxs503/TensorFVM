"""Gates for the two-grid fall-back band of ``richardson_gci``.

The fall-back (formal order + safety factor 3) is the branch every broken
refinement study lands in, and it used to be reachable through two doors that
produced a *narrow* band:

* ``eps`` was the fine/medium difference only, so a non-monotone series whose two
  finest metrics cancel by accident reported a nearly zero band -- the opposite
  of "a broken study can never report a confident band";
* an order solve on a triplet with one vanishing difference returns ``p`` far
  above the formal order (the bracket runs to 40), and ``GCI ~ 1/(r^p-1)`` then
  collapses even though the triplet carries no order information.

The gates below pin the shipped behaviour: the plausibility window, the
worst-adjacent-change ``eps``, and -- the one that matters for the rest of the
repository -- the *monotone* path being bit-identical, so no already-published
band moves.  The measured before/after table lives in
``docs/gci-fallback-band/report.md`` and is regenerated by
``scripts/audit_gci_fallback_band.py``.
"""

from __future__ import annotations

import json
import math

import pytest

import importlib.util
from pathlib import Path

from tensorfvm.verification.richardson import (ORDER_CAP_ABS, ORDER_CAP_FACTOR,
                                               SAFETY_FALLBACK, SAFETY_OBSERVED,
                                               richardson_gci, reference_agreement)

UNIFORM = (0.1, 0.2, 0.4)
SCRIPT = Path(__file__).resolve().parents[1]/'scripts'/'audit_gci_fallback_band.py'


def _audit_module():
    spec = importlib.util.spec_from_file_location('audit_gci_fallback_band', SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_monotone_path_is_bit_identical():
    """The fix must not move a single band on a genuine ``C h^p`` sequence."""
    for order in (1., 1.5, 2., 3.):
        for ratio in (1.5, 2., 3.):
            h = (0.1, 0.1*ratio, 0.1*ratio*ratio)
            values = [1. + .4*x**order for x in h]
            study = richardson_gci(*values, h, theory_order=order)
            eps = abs((values[1]-values[0])/values[0])
            expected = SAFETY_OBSERVED*eps/(ratio**order-1.)
            assert study.convergence == 'monotone'
            assert study.fallback_reason == 'none'
            assert study.safety_factor == SAFETY_OBSERVED
            assert study.gci == pytest.approx(expected, rel=1e-12)


def test_vanishing_first_difference_is_not_order_information():
    """``f1 ~ f2`` with ``f3`` far away must not produce a razor-thin band."""
    values = (1.10, 1.1001, 1.30)
    study = richardson_gci(*values, UNIFORM, theory_order=2.)
    assert study.convergence == 'order-implausible'
    assert study.fallback_reason == 'implausible-order'
    assert math.isnan(study.order) is False and study.order > ORDER_CAP_FACTOR*2.
    assert study.order_used == 2. and study.safety_factor == SAFETY_FALLBACK
    assert study.order_limit == pytest.approx(ORDER_CAP_FACTOR*2.)
    agreement = reference_agreement(study, 1.)
    assert agreement['band_covered'] and agreement['efficiency_index'] <= 1.
    assert agreement['fallback_reason'] == 'implausible-order'


def test_plausibility_window_uses_absolute_cap_without_formal_order():
    values = (1.10, 1.1001, 1.30)
    study = richardson_gci(*values, UNIFORM)
    assert study.order_limit == pytest.approx(ORDER_CAP_ABS)
    assert study.convergence == 'order-implausible'
    assert study.order_used == 1.  # no formal order was declared


def test_fallback_eps_is_the_worst_adjacent_change():
    """A coarse-grid outlier must widen the band, not be hidden by f1 ~ f2."""
    values = (1., 0.99, 1.30)
    study = richardson_gci(*values, UNIFORM, theory_order=2.)
    assert study.convergence == 'inconsistent'
    worst = max(abs(values[1]-values[0]), abs(values[2]-values[1]))/abs(values[0])
    expected = SAFETY_FALLBACK*worst/((UNIFORM[1]/UNIFORM[0])**2.-1.)
    assert study.gci == pytest.approx(expected, rel=1e-12)
    # ... and this is wider than the old fine/medium-only rule.
    old = SAFETY_FALLBACK*abs((values[1]-values[0])/values[0])/((UNIFORM[1]/UNIFORM[0])**2.-1.)
    assert study.gci > 5.*old


def test_sign_alternating_series_band_is_now_a_bound():
    """The repository's own negative control had efficiency index just above 1."""
    values = (.1, .08, .09)
    study = richardson_gci(*values, UNIFORM, theory_order=2.)
    assert study.convergence == 'inconsistent' and study.safety_factor == SAFETY_FALLBACK
    assert study.gci == pytest.approx(.2)  # unchanged: fine/medium was already the worst
    agreement = reference_agreement(study, .1)
    assert agreement['efficiency_index'] <= 1.


def test_audit_summary_is_reproducible_and_shows_the_fix():
    """The audit script's own verdicts, recomputed here (cheap, pure NumPy)."""
    module = _audit_module()
    rows = {row['family']: row for row in module.summarise(module.evaluate())}
    # Monotone control untouched; fall-back families never lose coverage and end
    # up as bounds (efficiency <= 1); the collapsing family gains coverage.
    assert rows['F-control']['unchanged_gci'] == rows['F-control']['cases']
    for family in ('F-signed', 'F-phaselock', 'F-implausible'):
        row = rows[family]
        assert row['coverage_after'] >= row['coverage_before']
        assert row['worst_efficiency_after'] <= 1.
        assert row['median_band_ratio'] >= 1.
    collapsed = rows['F-implausible']
    assert collapsed['coverage_before'] == 0. and collapsed['coverage_after'] == 1.
    assert collapsed['worst_efficiency_before'] > 1e6


def test_audit_payload_is_json_serialisable():
    module = _audit_module()
    records = module.evaluate()
    payload = dict(case_count=len(records), families=module.summarise(records),
                   excerpt=records[:4])
    json.dumps(payload, allow_nan=True)