"""Reproducible Gmsh OCC body-fitted tetrahedra around bare SUBOFF.

A segmented interpolating spline of the analytic mother meridian is revolved
and subtracted from the far-field box. No Cartesian immersed approximation.
Boundary layers are not generated by this initial geometry preparation.
"""
from pathlib import Path
import numpy as np
from .suboff_geometry import radius, LENGTH_FT


def generate_suboff_mesh(path, *, wall_size=.035, far_size=.35, stations=65):
    import gmsh
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if wall_size <= 0 or far_size < wall_size or stations < 9:
        raise ValueError('positive wall size, larger far size, and >=9 stations required')
    gmsh.initialize()
    try:
        gmsh.option.setNumber('General.Terminal', 0)
        gmsh.option.setNumber('General.NumThreads', 1)
        gmsh.option.setNumber('Mesh.RandomSeed', 1)
        gmsh.model.add('suboff_aff1')
        occ=gmsh.model.occ
        breaks=np.array([0,3.333333,10.645833,13.979167,LENGTH_FT])/LENGTH_FT
        curves=[]; pts=[]
        for k,(a,b) in enumerate(zip(breaks[:-1],breaks[1:])):
            x=a+(b-a)*.5*(1-np.cos(np.linspace(0,np.pi,stations)))
            tags=[]
            for j,v in enumerate(x):
                if k and j==0:
                    tags.append(pts[-1]); continue
                r=float(radius(v))
                if v==0 or v==1: r=0.
                tags.append(occ.addPoint(float(v),r,0))
            curves.append(occ.addSpline(tags)); pts.extend(tags if not k else tags[1:])
        axis=occ.addLine(pts[-1],pts[0])
        face=occ.addPlaneSurface([occ.addCurveLoop(curves+[axis])])
        revolved=occ.revolve([(2,face)],0,0,0,1,0,0,2*np.pi)
        hull=[e for e in revolved if e[0]==3]
        box=occ.addBox(-1,-1,-1,4,2,2)
        fluid,_=occ.cut([(3,box)],hull)
        occ.synchronize()
        patches={'wall':[],'inlet':[],'outlet':[],'farfield':[]}
        for dim,tag in gmsh.model.getBoundary(fluid,oriented=False):
            bounds=occ.getBoundingBox(dim,tag)
            if abs(bounds[0]+1)<1e-6 and abs(bounds[3]+1)<1e-6: p='inlet'
            elif abs(bounds[0]-3)<1e-6 and abs(bounds[3]-3)<1e-6: p='outlet'
            elif max(abs(bounds[1]),abs(bounds[2]),abs(bounds[4]),abs(bounds[5]))>.5: p='farfield'
            else: p='wall'
            patches[p].append(tag)
        for i,(name,tags) in enumerate(patches.items(),1):
            gmsh.model.addPhysicalGroup(2,tags,i,name)
        gmsh.model.addPhysicalGroup(3,[v[1] for v in fluid],10,'fluid')
        distance=gmsh.model.mesh.field.add('Distance')
        gmsh.model.mesh.field.setNumbers(distance,'FacesList',patches['wall'])
        gmsh.model.mesh.field.setNumber(distance,'Sampling',100)
        threshold=gmsh.model.mesh.field.add('Threshold')
        for name,val in [('InField',distance),('SizeMin',wall_size),('SizeMax',far_size),('DistMin',.04),('DistMax',.4)]:
            gmsh.model.mesh.field.setNumber(threshold,name,val)
        gmsh.model.mesh.field.setAsBackgroundMesh(threshold)
        gmsh.option.setNumber('Mesh.MeshSizeFromPoints',0)
        gmsh.option.setNumber('Mesh.MeshSizeFromCurvature',0)
        gmsh.option.setNumber('Mesh.MeshSizeExtendFromBoundary',0)
        gmsh.option.setNumber('Mesh.Algorithm3D',1)
        gmsh.model.mesh.generate(3)
        gmsh.model.mesh.optimize('Netgen')
        gmsh.write(str(path))
        tags,coords,_=gmsh.model.mesh.getNodes()
        etypes,etags,_=gmsh.model.mesh.getElements(3)
        wall_nodes=[]
        for s in patches['wall']:
            _,c,_=gmsh.model.mesh.getNodes(2,s,includeBoundary=True)
            wall_nodes.extend(np.asarray(c).reshape(-1,3))
        wall_nodes=np.asarray(wall_nodes)
        radial=np.linalg.norm(wall_nodes[:,1:],axis=1)
        deviation=np.abs(radial-radius(wall_nodes[:,0]))
        return {'nodes':len(tags),'cells':sum(len(t) for t in etags),'element_types':list(map(int,etypes)),
                'patch_surfaces':{k:len(v) for k,v in patches.items()},'max_wall_radial_error_L':float(deviation.max()),
                'wall_size_L':wall_size,'far_size_L':far_size,'stations_per_segment':stations,
                'gmsh_version':gmsh.__version__,'boundary_layer':False,'physics_qualified':False}
    finally:
        gmsh.finalize()
