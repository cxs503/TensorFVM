"""Reproduce docs/ci-lint-cleanup/ruff_baseline_vs_after.png.

Baseline counts come from the pristine `main` tree:

    git archive main src tests scripts pyproject.toml | tar -x -C /tmp/tfvm_head
    (cd /tmp/tfvm_head && ruff check src tests scripts --statistics)

After-counts come from the cleaned working tree, generated by the same command.
Usage: python docs/ci-lint-cleanup/make_figure.py <baseline_stats.txt>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

OUT = Path(__file__).with_name("ruff_baseline_vs_after.png")


def parse(path: Path) -> dict[str, int]:
    rows: dict[str, int] = {}
    for line in path.read_text().splitlines():
        match = re.match(r"\s*(\d+)\s+([A-Z]\d+)\s+\[.\]\s+", line)
        if match:
            rows[match.group(2)] = int(match.group(1))
    return rows


def main() -> None:
    baseline = parse(Path(sys.argv[1]))
    codes = sorted(baseline, key=lambda code: -baseline[code])
    values = [baseline[code] for code in codes]
    fig, ax = plt.subplots(figsize=(7.5, 4.2))
    ax.bar(codes, values, color="#c1440e", label="main @ d8fb330c (before)")
    ax.bar(codes, [0] * len(codes), color="#2b6cb0", label="agent/m4057 (after)")
    for code, value in zip(codes, values, strict=True):
        ax.annotate(
            str(value),
            (code, value),
            textcoords="offset points",
            xytext=(0, 3),
            ha="center",
            fontsize=8,
        )
    ax.set_yscale("symlog", linthresh=1)
    ax.set_ylabel("ruff findings (symlog)")
    ax.set_title(f"TensorFVM ruff backlog: {sum(values)} -> 0 findings")
    ax.legend(loc="upper right", fontsize=8)
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT, dpi=160)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
