"""Run a wall-resolved 30P30N three-element airfoil diagnostic case.

Gmsh is an optional mesh-generation executable.  A pre-generated ASCII Gmsh v2
mesh can instead be supplied with ``--mesh-file``.  The flow solve uses the
existing two-dimensional collocated SIMPLE/Spalart--Allmaras implementation.
"""

import argparse
import csv
import json
import math
import shutil
import subprocess
from dataclasses import asdict
from pathlib import Path

import torch

from .solver import SimpleSolver, SolverConfig


REFERENCE_LIFT = 2.167089
REFERENCE_DRAG_REPORTED = 0.033243
PROFILE_DIRECTORY = Path(__file__).with_name("data") / "30p30n"
NORMALIZED_NOMINAL_CHORD = 1 / 1.216241


def _read_profile(path: Path) -> list[tuple[float, float]]:
    points = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.split("#", 1)[0].strip()
        if not stripped:
            continue
        fields = stripped.replace(",", " ").split()
        if len(fields) < 2:
            raise ValueError(f"{path}:{line_number}: expected x and y coordinates")
        try:
            point = (float(fields[0]), float(fields[1]))
        except ValueError as exc:
            raise ValueError(f"{path}:{line_number}: invalid coordinate") from exc
        if not all(math.isfinite(value) for value in point):
            raise ValueError(f"{path}:{line_number}: nonfinite coordinate")
        points.append(point)
    if len(points) < 3:
        raise ValueError(f"{path}: profile must have at least three points")
    if math.dist(points[0], points[-1]) < 1e-12:
        points.pop()
    if len(points) < 3:
        raise ValueError(f"{path}: profile must have at least three distinct points")
    area = 0.5 * sum(
        x0 * y1 - x1 * y0
        for (x0, y0), (x1, y1) in zip(points, points[1:] + points[:1])
    )
    if abs(area) < 1e-12:
        raise ValueError(f"{path}: profile has zero enclosed area")
    return points


def _minimum_profile_gap(first, second) -> float:
    """Return the minimum distance between two polygonal profile boundaries."""
    def point_segment_distance(point, start, stop):
        edge = (stop[0] - start[0], stop[1] - start[1])
        length_squared = edge[0] ** 2 + edge[1] ** 2
        fraction = (((point[0] - start[0]) * edge[0]
                     + (point[1] - start[1]) * edge[1]) / length_squared)
        fraction = min(1.0, max(0.0, fraction))
        closest = (start[0] + fraction * edge[0], start[1] + fraction * edge[1])
        return math.dist(point, closest)

    first_edges = list(zip(first, first[1:] + first[:1]))
    second_edges = list(zip(second, second[1:] + second[:1]))
    return min(
        min(point_segment_distance(point, *edges)
            for point in points for edges in segments)
        for points, segments in ((first, second_edges), (second, first_edges))
    )


def write_gmsh_geo(destination: str | Path, *, domain=(-5.0, 5.0, -5.0, 5.0),
                   near_size=0.0015, far_size=0.08, first_layer=1e-5,
                   layer_thickness=0.004, layer_ratio=1.2, profile_directory=None) -> Path:
    """Write a 30P30N Gmsh .geo model with three separate wall boundaries."""
    destination = Path(destination)
    xmin, xmax, ymin, ymax = map(float, domain)
    values = (xmin, xmax, ymin, ymax, near_size, far_size, first_layer,
              layer_thickness, layer_ratio)
    if not all(math.isfinite(value) for value in values):
        raise ValueError("domain and mesh sizes must be finite")
    if not xmin < xmax or not ymin < ymax:
        raise ValueError("mesh domain bounds must be ordered")
    if min(near_size, far_size, first_layer, layer_thickness, layer_ratio) <= 0:
        raise ValueError("mesh sizes, boundary-layer thickness, and ratio must be positive")
    profile_directory = PROFILE_DIRECTORY if profile_directory is None else Path(profile_directory)
    profiles = {
        name: _read_profile(profile_directory / f"{name}.dat")
        for name in ("slat", "main", "flap")
    }
    minimum_gap = min(
        _minimum_profile_gap(profiles[first], profiles[second])
        for first, second in (("slat", "main"), ("main", "flap"), ("slat", "flap"))
    )
    if 2 * layer_thickness >= minimum_gap:
        raise ValueError(
            f"layer_thickness must be less than half the minimum element gap "
            f"({minimum_gap / 2:.6g}) to keep the Gmsh wall layers separate"
        )
    if any(not (xmin < x < xmax and ymin < y < ymax)
           for points in profiles.values() for x, y in points):
        raise ValueError("outer domain must strictly contain all 30P30N profiles")

    lines = [
        "// Generated by tensorfvm.benchmark_30p30n; profiles are separate holes.",
        "SetFactory(\"Built-in\");",
        f"Mesh.CharacteristicLengthMin = {first_layer:.12g};",
        f"Mesh.CharacteristicLengthMax = {far_size:.12g};",
        "Mesh.MeshSizeFromPoints = 0;",
        "Mesh.MeshSizeFromCurvature = 0;",
        "Mesh.MeshSizeExtendFromBoundary = 0;",
        "Mesh.Algorithm = 6;",
        "Mesh.ElementOrder = 1;",
        "Mesh.SaveAll = 0;",
    ]
    next_point = 1
    next_curve = 1
    next_loop = 1
    body_curves: dict[str, list[int]] = {}
    loop_ids: dict[str, int] = {}
    for name, points in profiles.items():
        point_ids = list(range(next_point, next_point + len(points)))
        next_point += len(points)
        for point_id, (x, y) in zip(point_ids, points):
            lines.append(
                f"Point({point_id}) = {{{x:.16g}, {y:.16g}, 0, {near_size:.12g}}};"
            )
        curve_ids = list(range(next_curve, next_curve + len(points)))
        next_curve += len(points)
        for curve_id, start, stop in zip(curve_ids, point_ids,
                                         point_ids[1:] + point_ids[:1]):
            lines.append(f"Line({curve_id}) = {{{start}, {stop}}};")
        loop_id = next_loop
        next_loop += 1
        lines.append(f"Curve Loop({loop_id}) = {{{', '.join(map(str, curve_ids))}}};")
        body_curves[name] = curve_ids
        loop_ids[name] = loop_id

    corner_ids = list(range(next_point, next_point + 4))
    next_point += 4
    for point_id, (x, y) in zip(corner_ids, ((xmin, ymin), (xmax, ymin),
                                             (xmax, ymax), (xmin, ymax))):
        lines.append(f"Point({point_id}) = {{{x:.16g}, {y:.16g}, 0, {far_size:.12g}}};")
    outer_curves = list(range(next_curve, next_curve + 4))
    for curve_id, start, stop in zip(outer_curves, corner_ids,
                                     corner_ids[1:] + corner_ids[:1]):
        lines.append(f"Line({curve_id}) = {{{start}, {stop}}};")
    outer_loop = next_loop
    lines.append(f"Curve Loop({outer_loop}) = {{{', '.join(map(str, outer_curves))}}};")
    loops = [outer_loop, loop_ids["slat"], loop_ids["main"], loop_ids["flap"]]
    lines.append(f"Plane Surface(1) = {{{', '.join(map(str, loops))}}};")
    lines.extend([
        f"Physical Curve(\"far-field\") = {{{outer_curves[0]}, {outer_curves[2]}}};",
        f"Physical Curve(\"outlet\") = {{{outer_curves[1]}}};",
        f"Physical Curve(\"inlet\") = {{{outer_curves[3]}}};",
        f"Physical Curve(\"slat\") = {{{', '.join(map(str, body_curves['slat']))}}};",
        f"Physical Curve(\"main\") = {{{', '.join(map(str, body_curves['main']))}}};",
        f"Physical Curve(\"flap\") = {{{', '.join(map(str, body_curves['flap']))}}};",
        "Physical Surface(\"fluid\") = {1};",
        "Field[1] = Distance;",
        "Field[1].CurvesList = {" + ", ".join(
            str(curve) for curves in body_curves.values() for curve in curves
        ) + "};",
        "Field[1].Sampling = 100;",
        "Field[2] = Threshold;",
        "Field[2].InField = 1;",
        f"Field[2].SizeMin = {near_size:.12g};",
        f"Field[2].SizeMax = {far_size:.12g};",
        f"Field[2].DistMin = {layer_thickness:.12g};",
        f"Field[2].DistMax = {max(10 * layer_thickness, 0.25):.12g};",
        "Background Field = 2;",
        "Field[3] = BoundaryLayer;",
        "Field[3].CurvesList = {" + ", ".join(
            str(curve) for curves in body_curves.values() for curve in curves
        ) + "};",
        f"Field[3].hwall_n = {first_layer:.12g};",
        f"Field[3].thickness = {layer_thickness:.12g};",
        f"Field[3].ratio = {layer_ratio:.12g};",
        "Field[3].Quads = 1;",
        "BoundaryLayer Field = 3;",
    ])
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return destination


def _generate_mesh(output: Path, *, near_size: float, far_size: float,
                   first_layer: float, layer_thickness: float) -> Path:
    executable = shutil.which("gmsh")
    if executable is None:
        raise RuntimeError("Gmsh is required to generate the 30P30N mesh; install gmsh "
                           "or pass --mesh-file with an ASCII Gmsh v2 mesh")
    geo = write_gmsh_geo(output / "30p30n.geo", near_size=near_size,
                         far_size=far_size, first_layer=first_layer,
                         layer_thickness=layer_thickness)
    mesh_path = output / "mesh.msh"
    process = subprocess.run(
        [executable, str(geo), "-2", "-format", "msh2", "-o", str(mesh_path)],
        capture_output=True, text=True, check=False,
    )
    if process.returncode != 0 or not mesh_path.is_file():
        detail = (process.stderr or process.stdout).strip()
        raise RuntimeError(f"Gmsh failed to generate the three-element mesh: {detail}")
    return mesh_path


def compare_30p30n(result) -> dict:
    """Diagnostic comparison with correctly identified Wolf Dynamics values.

    Wolf Dynamics identifies Cl=2.167089 and Cd=0.033243. The derivative
    validation-repository README swapped the labels; it is not authoritative.
    These are graph readings, not an independently qualified reference dataset.
    Nominal stowed chord, geometry, Re and boundary conditions must also match.
    """
    computed = result.aerodynamic_coefficients or {}
    lift = float(computed.get("lift", math.nan))
    drag = float(computed.get("drag", math.nan))
    valid = math.isfinite(lift) and math.isfinite(drag)
    config = getattr(result, 'config', None)
    conditions_match = config is None or (
        math.isclose(config.reynolds, 5_000_000) and
        math.isclose(config.angle_of_attack, 0, abs_tol=1e-10))
    return {
        "computed_coefficients": {
            "lift": lift if valid else None,
            "drag": drag if valid else None,
            "drag_x100": 100 * drag if valid else None,
        },
        "reference": {"lift": REFERENCE_LIFT,
                      "drag_reported": REFERENCE_DRAG_REPORTED},
        "relative_errors": {
            "lift": abs(lift - REFERENCE_LIFT) / abs(REFERENCE_LIFT)
            if valid and conditions_match else None,
            "drag_if_source_is_dimensionless": abs(drag - REFERENCE_DRAG_REPORTED)
            / abs(REFERENCE_DRAG_REPORTED) if valid and conditions_match else None,
        },
        "reynolds_alpha_match": conditions_match,
        "source_url": "https://www.wolfdynamics.com/tutorials.html?id=119",
        "note": "Diagnostic comparison only: graph-reading uncertainty, nominal "
                "stowed chord and matched geometry/conditions require verification. "
                "Cl/Cd labels corrected from the original Wolf Dynamics table.",
    }


def export_result(result, directory: str | Path, *, wall_pressure=None) -> None:
    """Write the unstructured solution, element Cp, force and residual files."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    mesh = result.mesh
    centers = mesh.centers.reshape(-1, 2).detach().cpu()
    u, v, pressure = (field.reshape(-1).detach().cpu()
                      for field in (result.u, result.v, result.p))
    turbulence = (result.nu_tilde.reshape(-1).detach().cpu()
                  if result.nu_tilde is not None else None)
    eddy_viscosity = (result.turbulent_kinematic_viscosity.reshape(-1).detach().cpu()
                      if result.turbulent_kinematic_viscosity is not None else None)
    with (directory / "fields.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        header = ["cell", "x", "y", "u", "v", "p", "speed"]
        if turbulence is not None:
            header.extend(("nu_tilde", "nu_t"))
        writer.writerow(header)
        for index, point in enumerate(centers):
            row = [index, float(point[0]), float(point[1]), float(u[index]),
                   float(v[index]), float(pressure[index]),
                   math.hypot(float(u[index]), float(v[index]))]
            if turbulence is not None:
                row.extend((float(turbulence[index]), float(eddy_viscosity[index])))
            writer.writerow(row)

    vertices = mesh.vertices.detach().cpu()
    with (directory / "nodes.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(("node", "x", "y"))
        for index, point in enumerate(vertices):
            writer.writerow((index, float(point[0]), float(point[1])))
    with (directory / "cells.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(("cell", "node0", "node1", "node2", "node3"))
        for index, cell in enumerate(mesh.cell_nodes):
            writer.writerow((index, *cell, *([""] * (4 - len(cell)))))

    face_centers = mesh.face_centers.detach().cpu()
    owners = mesh.owner.detach().cpu()
    masks = mesh.masks
    if wall_pressure is not None:
        wall_pressure=wall_pressure.detach().cpu().reshape(-1)
        if len(wall_pressure)!=len(owners) or not bool(torch.isfinite(wall_pressure).all()):
            raise ValueError('Invalid solver face-pressure field')
        with (directory/'wall-face-pressure.csv').open('w',newline='',encoding='utf-8') as stream:
            writer=csv.writer(stream);writer.writerow(('face','p'))
            for face_id in torch.nonzero(masks['wall']).flatten().tolist():
                writer.writerow((face_id,float(wall_pressure[face_id])))
    with (directory / "surface.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(("element", "x", "y", "p", "cp"))
        dynamic_pressure = 0.5 * result.config.density * result.config.inlet_velocity ** 2
        for name in ("slat", "main", "flap"):
            mask = masks[name].detach().cpu()
            for face_id in torch.nonzero(mask, as_tuple=False).flatten().tolist():
                owner = int(owners[face_id])
                point = face_centers[face_id]
                value = float(pressure[owner]) if wall_pressure is None else float(wall_pressure[face_id])
                writer.writerow((name, float(point[0]), float(point[1]), value,
                                 value / dynamic_pressure))

    (directory / "history.json").write_text(
        json.dumps(result.history, indent=2, allow_nan=False) + "\n", encoding="utf-8"
    )
    comparison = compare_30p30n(result)
    summary = {
        "benchmark": f"MDA-30P30N-Re{result.config.reynolds:g}-alpha{result.config.angle_of_attack:g}",
        "converged": result.converged,
        "iterations": len(result.history),
        "config": asdict(result.config),
        "mesh": {"nodes": int(len(mesh.vertices)), "cells": len(mesh.cell_nodes),
                 "boundary_faces": {name: int(mesh.masks[name].sum())
                                     for name in ("slat", "main", "flap", "inlet",
                                                  "outlet", "far-field")}},
        "final_residuals": result.history[-1] if result.history else {},
        "aerodynamic_coefficients": result.aerodynamic_coefficients,
        "surface_forces": result.surface_forces,
        "reference_comparison": comparison,
        "physics_acceptance": "diagnostic-only; not a validated match",
    }
    (directory / "benchmark.json").write_text(
        json.dumps(summary, indent=2, allow_nan=False) + "\n", encoding="utf-8"
    )
    report = f"""MDA 30P30N 三段翼流动诊断
============================

Re={result.config.reynolds:g}，攻角={result.config.angle_of_attack:g}°，
参考弦长={result.config.reference_length:g}。数值收敛={result.converged}，
完成迭代={len(result.history)}。实际计算数据在 fields.csv 和 surface.csv。

当前 Cl={comparison['computed_coefficients']['lift']:.8g}，
Cd={comparison['computed_coefficients']['drag']:.8g}。
Wolf Dynamics 原表为 Cl=2.167089，Cd=0.033243；旧派生资料误将标签抄反。
该参考来自图上读取，几何、收起状态参考弦长及工况仍需独立匹配，不能只凭
系数接近或迭代收敛授予物理精度资格。正式压力对比另行记录来源与工况。
"""
    (directory / "report.rst").write_text(report, encoding="utf-8")


def run_benchmark(directory: str | Path, *, max_iterations: int = 1000,
                  mesh_file: str | Path | None = None, device: str = "cpu",
                  tolerance: float = 1e-5, near_size: float = 0.0015,
                  far_size: float = 0.08, first_layer: float = 1e-5,
                  layer_thickness: float = 0.004) -> dict:
    """Run the public-geometry 30P30N case and retain convergence diagnostics."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    if mesh_file is None:
        mesh_path = _generate_mesh(directory, near_size=near_size, far_size=far_size,
                                   first_layer=first_layer,
                                   layer_thickness=layer_thickness)
    else:
        mesh_path = Path(mesh_file)
        if not mesh_path.is_file():
            raise ValueError(f"mesh file does not exist: {mesh_path}")

    config = SolverConfig(
        nx=1, ny=1, length=10.0, height=10.0,
        cylinder_radius=None, mesh_type="three-element", mesh_file=str(mesh_path),
        airfoil_chord=NORMALIZED_NOMINAL_CHORD, inlet_velocity=1.0, density=1.0,
        reynolds=5_000_000.0, angle_of_attack=0.0,
        turbulence_model="spalart-allmaras", sa_freestream_ratio=3.0,
        velocity_relaxation=0.3, pressure_relaxation=0.2,
        turbulence_relaxation=0.3, pseudo_time_step=0.02,
        tolerance=tolerance, max_iterations=max_iterations, device=device,
    )
    result = SimpleSolver(config).solve()
    export_result(result, directory)
    return {
        "benchmark": "MDA-30P30N-Re5000000-alpha0",
        "converged": bool(result.converged),
        "iterations": len(result.history),
        "aerodynamic_coefficients": result.aerodynamic_coefficients,
        "reference_comparison": compare_30p30n(result),
        "mesh_file": str(mesh_path),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="MDA 30P30N three-element airfoil (2-D diagnostic case)"
    )
    parser.add_argument("--output", type=Path, default=Path("results/30p30n"))
    parser.add_argument("--mesh-file", type=Path,
                        help="reuse an ASCII Gmsh v2 mesh instead of invoking gmsh")
    parser.add_argument("--max-iterations", type=int, default=1000)
    parser.add_argument("--tolerance", type=float, default=1e-5)
    parser.add_argument("--device", default="cpu", help="cpu or cuda")
    parser.add_argument("--near-size", type=float, default=0.0015)
    parser.add_argument("--far-size", type=float, default=0.08)
    parser.add_argument("--first-layer", type=float, default=1e-5,
                        help="first wall-normal cell height used by the Gmsh boundary layer")
    parser.add_argument("--layer-thickness", type=float, default=0.004)
    args = parser.parse_args(argv)
    torch.set_num_threads(1)
    try:
        summary = run_benchmark(
            args.output, max_iterations=args.max_iterations, mesh_file=args.mesh_file,
            device=args.device, tolerance=args.tolerance, near_size=args.near_size,
            far_size=args.far_size, first_layer=args.first_layer,
            layer_thickness=args.layer_thickness,
        )
    except (ValueError, RuntimeError, OSError) as error:
        parser.exit(1, f"30P30N case failed: {error}\n")
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0 if summary["converged"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
